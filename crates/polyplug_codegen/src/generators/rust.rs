/// Generate one guest-side host contract caller struct.
fn generate_guest_host_contract_caller(
    out: &mut String,
    contract: &ResolvedHostContract,
) -> Result<(), PolyplugcError> {
    let caller_name: String = host_contract_name_to_caller(&contract.name);
    let needs_arena: bool = contract.functions.iter().any(fn_needs_arena);

    // langprint renders the caller struct FORM (fields + docs); rustfmt canonicalizes.
    let mut struct_docs: Vec<String> = vec![format!(
        "Guest caller for host contract `{}` (id=0x{:016X})",
        contract.name, contract.contract_id
    )];
    append_lines(&mut struct_docs, contract.docs.as_deref());
    if needs_arena {
        struct_docs.extend([
            String::new(),
            "# Call-arena lifetime".to_owned(),
            String::new(),
            "Methods returning variable-size values (`StringView`, `Buffer`, or structs".to_owned(),
            "that may embed one) take `&mut self` and reset this caller's arena at the".to_owned(),
            "start of the call. Any view returned by such a method borrows arena memory".to_owned(),
            "and is valid only until the next arena-backed call on the same caller.".to_owned(),
        ]);
    }
    let mut fields: Vec<RustField> = vec![
        RustField {
            name: "interface".to_owned(),
            field_type: "*const HostContractInterface".to_owned(),
            visibility: RustVisibility::Private,
            attributes: Vec::new(),
            docs: Some(vec![
                "Vtable for the host contract: provides dispatch metadata and function pointers."
                    .to_owned(),
                "Resolved via `HostApi::resolve_host_contract_interface`.".to_owned(),
            ]),
        },
        RustField {
            name: "instance".to_owned(),
            field_type: "HostContractInstance".to_owned(),
            visibility: RustVisibility::Private,
            attributes: Vec::new(),
            docs: Some(vec![
                "Per-instance state for the host contract, produced by".to_owned(),
                "`HostApi::get_host_contract`. Passed as the first argument to native".to_owned(),
                "dispatch functions (the host thunk dereferences it as the implementation pointer)."
                    .to_owned(),
            ]),
        },
        RustField {
            name: "host".to_owned(),
            field_type: "*const HostApi".to_owned(),
            visibility: RustVisibility::Private,
            attributes: Vec::new(),
            docs: Some(vec![
                "Host interface pointer captured in `from_host` — used for cross-boundary"
                    .to_owned(),
                "string allocation when marshalling StringView parameters.".to_owned(),
            ]),
        },
    ];
    if needs_arena {
        fields.push(RustField {
            name: "arena_buf".to_owned(),
            field_type: "Box<[u8; CALL_ARENA_BUF_LEN]>".to_owned(),
            visibility: RustVisibility::Private,
            attributes: Vec::new(),
            docs: Some(vec![
                "Stable-address backing buffer for the per-call arena. Boxed so the".to_owned(),
                "arena's interior pointers stay valid when the caller is moved.".to_owned(),
            ]),
        });
        fields.push(RustField {
            name: "arena".to_owned(),
            field_type: "CallArena".to_owned(),
            visibility: RustVisibility::Private,
            attributes: Vec::new(),
            docs: Some(vec![
                "Per-call bump arena over `arena_buf`, reset at each arena-backed call.".to_owned(),
            ]),
        });
    }
    let caller_struct: RustStruct = RustStruct {
        name: caller_name.clone(),
        visibility: RustVisibility::Pub,
        generic_args: Vec::new(),
        fields,
        methods: Vec::new(),
        derives: Vec::new(),
        attributes: Vec::new(),
        is_tuple: false,
        docs: Some(struct_docs),
    };
    out.push_str(&render_rust_host_struct(&caller_struct)?);
    out.push_str("\n\n");

    // The impl shell stays hand-emitted; langprint renders each member fn below.
    out.push_str(&format!("impl {caller_name} {{\n"));

    // from_host — factory that resolves the host-contract vtable + instance.
    let mut from_host_body: String = String::new();
    from_host_body.push_str("if host.is_null() {\n");
    from_host_body.push_str("return None;\n");
    from_host_body.push_str("}\n");
    from_host_body.push_str("// SAFETY: host is non-null and valid per ABI contract.\n");
    from_host_body.push_str("let host: &HostApi = unsafe { &*host };\n");
    from_host_body
        .push_str("// Resolve the contract vtable. This is the source of dispatch metadata\n");
    from_host_body.push_str("// (dispatch_type, function_count, functions) — NOT the instance.\n");
    from_host_body.push_str(
        "// SAFETY: `host` is the reborrowed non-null HostApi; resolve_host_contract_interface\n",
    );
    from_host_body.push_str(
        "// is an ABI function pointer safe to call with a valid host (returns null if absent).\n",
    );
    from_host_body.push_str("let interface: *const HostContractInterface = unsafe {\n");
    from_host_body.push_str(&format!(
        "(host.resolve_host_contract_interface)(host, 0x{:016X}_u64, min_version)\n",
        contract.contract_id
    ));
    from_host_body.push_str("};\n");
    from_host_body.push_str("if interface.is_null() {\n");
    from_host_body.push_str("return None;\n");
    from_host_body.push_str("}\n");
    from_host_body
        .push_str("// Obtain the per-instance state. Native dispatch functions receive this\n");
    from_host_body
        .push_str("// pointer as their first argument; the host thunk dereferences it.\n");
    from_host_body.push_str(
        "// SAFETY: `host` is the reborrowed non-null HostApi; get_host_contract is an ABI\n",
    );
    from_host_body.push_str(
        "// function pointer safe to call with a valid host (null-data instance if absent).\n",
    );
    from_host_body.push_str("let instance: HostContractInstance = unsafe {\n");
    from_host_body.push_str(&format!(
        "(host.get_host_contract)(host, 0x{:016X}_u64, min_version)\n",
        contract.contract_id
    ));
    from_host_body.push_str("};\n");
    if needs_arena {
        from_host_body
            .push_str("// Box the backing buffer first so the arena's interior pointers refer\n");
        from_host_body
            .push_str("// to a stable heap address that survives moving the caller value.\n");
        from_host_body.push_str(
            "let mut arena_buf: Box<[u8; CALL_ARENA_BUF_LEN]> = Box::new([0u8; CALL_ARENA_BUF_LEN]);\n",
        );
        from_host_body
            .push_str("let arena: CallArena = CallArena::new(arena_buf.as_mut_slice(), host);\n");
        from_host_body.push_str(&format!(
            "Some({caller_name} {{ interface, instance, host: host as *const HostApi, arena_buf, arena }})"
        ));
    } else {
        from_host_body.push_str(&format!(
            "Some({caller_name} {{ interface, instance, host: host as *const HostApi }})"
        ));
    }
    let from_host_fn: RustFunction = RustFunction {
        name: "from_host".to_owned(),
        visibility: RustVisibility::Pub,
        self_kind: RustSelfKind::None,
        parameters: vec![
            RustParameter {
                name: "host".to_owned(),
                param_type: "*const HostApi".to_owned(),
            },
            RustParameter {
                name: "min_version".to_owned(),
                param_type: "u32".to_owned(),
            },
        ],
        generic_args: Vec::new(),
        return_type: Some("Option<Self>".to_owned()),
        is_unsafe: true,
        is_async: false,
        is_const: false,
        abi: None,
        body: Some(vec![from_host_body]),
        attributes: Vec::new(),
        docs: Some(vec![
            "Factory method - creates caller from HostApi or None if not found.".to_owned(),
            String::new(),
            "# Safety".to_owned(),
            "The `host` pointer must be valid and non-null.".to_owned(),
        ]),
        comments: Vec::new(),
    };
    out.push_str(&render_rust_host_fn(&from_host_fn)?);
    out.push('\n');

    let is_valid_fn: RustFunction = RustFunction {
        name: "is_valid".to_owned(),
        visibility: RustVisibility::Pub,
        self_kind: RustSelfKind::Ref,
        parameters: Vec::new(),
        generic_args: Vec::new(),
        return_type: Some("bool".to_owned()),
        is_unsafe: false,
        is_async: false,
        is_const: false,
        abi: None,
        body: Some(vec!["!self.interface.is_null()".to_owned()]),
        attributes: Vec::new(),
        docs: Some(vec![
            "Check if caller is valid (resolved interface is non-null).".to_owned(),
        ]),
        comments: Vec::new(),
    };
    out.push_str(&render_rust_host_fn(&is_valid_fn)?);
    out.push('\n');

    for func in &contract.functions {
        generate_guest_host_contract_method(out, func, &caller_name)?;
    }

    out.push_str("}\n\n");
    Ok(())
}

/// Generate one method for a guest-side host contract caller.
fn generate_guest_host_contract_method(
    out: &mut String,
    func: &ResolvedFunction,
    caller_name: &str,
) -> Result<(), PolyplugcError> {
    let fn_id: u32 = func.function_id;
    let needs_arena: bool = fn_needs_arena(func);

    let parameters: Vec<RustParameter> = func
        .params
        .iter()
        .map(|p: &ResolvedParam| RustParameter {
            name: p.name.clone(),
            param_type: guest_param_type_name(&p.ty),
        })
        .collect::<Vec<RustParameter>>();

    let ret_type: String = match &func.returns {
        Some(ty) => guest_host_return_type_name(ty),
        None => "()".to_owned(),
    };

    // langprint renders the `pub fn name(&self, …) -> Result<…>` FORM; the dispatch
    // body below is built into `body` and rendered as the slot (rustfmt canonicalizes).
    let mut docs: Vec<String> = vec![format!(
        "Call host contract function `{}` (function_id={})",
        func.name, fn_id
    )];
    docs.extend(rust_function_docs(func));
    if needs_arena {
        docs.push("Returns a value borrowing this caller's arena; it stays valid until".to_owned());
        docs.push("the next arena-backed call on this caller.".to_owned());
    }

    let mut body: String = String::new();
    if needs_arena {
        body.push_str(
            "        // Reset the arena at call start: frees the previous call's overflow\n",
        );
        body.push_str(
            "        // blocks and rewinds the primary region, invalidating prior views.\n",
        );
        body.push_str("        self.arena.reset();\n");
    }

    body.push_str("        if self.interface.is_null() {\n");
    body.push_str(
        "            return Err(HostContractError::new(AbiErrorCode::HostContractNotFound));\n",
    );
    body.push_str("        }\n");

    body.push_str(
        "        // SAFETY: self.interface is non-null (checked above) and points to a valid\n",
    );
    body.push_str(
        "        // HostContractInterface produced by resolve_host_contract_interface.\n",
    );
    body.push_str(
        "        let interface: &HostContractInterface = unsafe { &*self.interface };\n\n",
    );

    emit_guest_host_contract_args_setup(&mut body, func, caller_name);

    emit_guest_host_contract_out_setup(&mut body, &func.returns);

    body.push_str("        let mut err: AbiError = AbiError::ok();\n");
    body.push_str(
        "        // SAFETY: args_ptr/out_ptr/&mut err match the host-contract ABI contract.\n",
    );
    body.push_str("        unsafe {\n");
    body.push_str("            match interface.dispatch_type {\n");
    body.push_str("                DispatchType::Native => {\n");
    // The function-id bounds check lives INSIDE the Native arm: reading
    // dispatch.native.function_count on a VM interface would alias bits of
    // dispatch.vm.call through the union (garbage). The VM-side loader
    // enforces its own bounds.
    body.push_str(&format!(
        "                    if interface.dispatch.native.function_count < {fn_id}_u32 + 1 {{\n"
    ));
    body.push_str(
        "                        return Err(HostContractError::new(AbiErrorCode::HostContractCallFailed));\n",
    );
    body.push_str("                    }\n");
    body.push_str(&format!(
        "                    let fn_ptr: *const () = *interface.dispatch.native.functions.add({fn_id}_usize);\n"
    ));
    body.push_str("                    // SAFETY: Transmuting *const () to a function pointer is sound because:\n");
    body.push_str("                    // - Function pointers have the same size and alignment as data pointers\n");
    body.push_str("                    // - The interface guarantees that the function at this index is a native dispatch\n");
    body.push_str("                    //   with the exact signature: unsafe extern \"C\" fn(*const (), *const (), *mut (), *mut AbiError)\n");
    body.push_str("                    let dispatch_fn: unsafe extern \"C\" fn(*const (), *const (), *mut (), *mut AbiError) = core::mem::transmute(fn_ptr);\n");
    body.push_str(
        "                    // The native thunk receives the per-instance state as its first\n",
    );
    body.push_str(
        "                    // argument and dereferences it as the implementation pointer.\n",
    );
    body.push_str(
        "                    dispatch_fn(self.instance.data as *const (), args_ptr, out_ptr, &mut err);\n",
    );
    body.push_str("                }\n");
    body.push_str("                DispatchType::VirtualMachine => {\n");
    let arena_arg: &str = if needs_arena {
        "&mut self.arena as *mut CallArena"
    } else {
        "core::ptr::null_mut()"
    };
    body.push_str(&format!(
        "                    (interface.dispatch.vm.call)(interface.user_data, interface.dispatch.vm.loader_data, GuestContractInstance::null(), {fn_id}_u32, args_ptr, out_ptr, {arena_arg}, &mut err);\n"
    ));
    body.push_str("                }\n");
    body.push_str("            }\n");
    body.push_str("        };\n\n");

    body.push_str("        if err.code != AbiErrorCode::Ok as u32 {\n");
    body.push_str("            let message: String = if err.message.ptr.is_null() || err.message.len == 0 {\n");
    body.push_str("                String::new()\n");
    body.push_str("            } else {\n");
    body.push_str("                // SAFETY: err.message.ptr is valid for err.message.len bytes and points to UTF-8 data.\n");
    body.push_str(
        "                // The message is owned by the producer (static or runtime-owned); the\n",
    );
    body.push_str(
        "                // receiver must NEVER free it. We only copy it into an owned String.\n",
    );
    body.push_str("                let s: String = unsafe {\n");
    body.push_str("                    let slice: &[u8] = core::slice::from_raw_parts(err.message.ptr, err.message.len);\n");
    body.push_str("                    core::str::from_utf8_unchecked(slice).to_owned()\n");
    body.push_str("                };\n");
    body.push_str("                s\n");
    body.push_str("            };\n");
    body.push_str("            return Err(HostContractError { code: AbiErrorCode::from_u32(err.code), message });\n");
    body.push_str("        }\n\n");

    emit_out_assume_init(&mut body, &func.returns);

    match &func.returns {
        Some(ResolvedTypeRef::AbiType(AbiBuiltin::StringView)) => {
            // A null/empty StringView (ptr=null, len=0) is a legal ABI return; constructing a
            // slice from a null pointer is UB even at len==0, so the empty case is guarded
            // explicitly. The non-empty branch keeps the raw construction because its lifetime
            // is tied to &mut self (the arena memory), not to the local out_val — calling
            // out_val.as_str() would borrow the local and not compile against the return type.
            body.push_str(
                "        // SAFETY: out_val.ptr points to host-owned memory that the contract guarantees\n\
                 \x20       // stays valid until the next arena-backed call on this caller. The returned &str\n\
                 \x20       // borrows &mut self, so the borrow checker forbids another call (which would reset\n\
                 \x20       // the arena and invalidate this memory) while the view is alive. A null/empty view\n\
                 \x20       // never dereferences the pointer; non-empty bytes are valid UTF-8 per TRUST_MODEL.\n\
                 \x20       let result: &str = if out_val.ptr.is_null() || out_val.len == 0 {\n\
                 \x20           \"\"\n\
                 \x20       } else {\n\
                 \x20           unsafe {\n\
                 \x20               let slice: &[u8] = core::slice::from_raw_parts(out_val.ptr, out_val.len);\n\
                 \x20               core::str::from_utf8_unchecked(slice)\n\
                 \x20           }\n\
                 \x20       };\n\
                 \x20       Ok(result)\n",
            );
        }
        Some(ResolvedTypeRef::AbiType(AbiBuiltin::Buffer)) => {
            // A null/empty Buffer (ptr=null, len=0) is a legal ABI return; from_raw_parts on a
            // null pointer is UB even at len==0, so the empty case is guarded explicitly. The
            // non-empty branch keeps the raw construction because its lifetime is tied to
            // &mut self, not to the local out_val.
            body.push_str(
                "        // SAFETY: out_val.ptr points to host-owned memory valid until the next arena-backed\n\
                 \x20       // call on this caller; the returned &[u8] borrows &mut self, so no second call can\n\
                 \x20       // invalidate it while the view is alive. A null/empty buffer never dereferences.\n\
                 \x20       let result: &[u8] = if out_val.ptr.is_null() || out_val.len == 0 {\n\
                 \x20           &[]\n\
                 \x20       } else {\n\
                 \x20           unsafe { core::slice::from_raw_parts(out_val.ptr, out_val.len) }\n\
                 \x20       };\n\
                 \x20       Ok(result)\n",
            );
        }
        Some(_) => {
            body.push_str("        Ok(out_val)\n");
        }
        None => {
            body.push_str("        Ok(())\n");
        }
    }

    if body.ends_with('\n') {
        body.pop();
    }
    let method: RustFunction = RustFunction {
        name: func.name.clone(),
        visibility: RustVisibility::Pub,
        self_kind: if needs_arena {
            RustSelfKind::RefMut
        } else {
            RustSelfKind::Ref
        },
        parameters,
        generic_args: Vec::new(),
        return_type: Some(format!("Result<{ret_type}, HostContractError>")),
        is_unsafe: false,
        is_async: false,
        is_const: false,
        abi: None,
        body: Some(vec![body]),
        attributes: Vec::new(),
        docs: Some(docs),
        comments: Vec::new(),
    };
    out.push_str(&render_rust_host_fn(&method)?);
    out.push('\n');
    Ok(())
}

/// Generate ergonomic guest-side type name for caller method parameters.
/// For guest callers, we use owned types where appropriate:
/// - StringView -> String (owned, passed as borrowed reference to ABI)
/// - Buffer -> Vec<u8> (owned, passed as borrowed reference to ABI)
/// - UserDefined -> TypeName (owned, passed by reference)
/// - Primitives -> T (passed by value)
fn guest_param_type_name(ty: &ResolvedTypeRef) -> String {
    match ty {
        ResolvedTypeRef::Primitive(p) => p.rust_name().to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => "String".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => "Vec<u8>".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Ptr) => "*mut ()".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Void) => "()".to_owned(),
        ResolvedTypeRef::UserDefined(name) => name.clone(),
    }
}

/// Map a guest→host caller return type to the emitted Rust type.
///
/// StringView and Buffer become borrowed slices (`&str` / `&[u8]`), whose
/// lifetime elides to `&mut self`. The borrow checker therefore enforces that
/// the view cannot outlive the next arena-backed call (which resets the arena).
/// All other types fall through to `rust_type_name`.
fn guest_host_return_type_name(ty: &ResolvedTypeRef) -> String {
    match ty {
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => "&str".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => "&[u8]".to_owned(),
        other => rust_type_name(other),
    }
}

/// Emit the args_ptr setup for a guest host contract method.
fn emit_guest_host_contract_args_setup(
    out: &mut String,
    func: &ResolvedFunction,
    caller_name: &str,
) {
    if func.params.is_empty() {
        out.push_str("        let args_ptr: *const () = core::ptr::null();\n");
        return;
    }

    // StringView parameters are copied into host-owned memory; the allocation
    // goes through the host pointer captured in `from_host` (no static storage).
    let any_string_view: bool = func
        .params
        .iter()
        .any(|p: &ResolvedParam| matches!(p.ty, ResolvedTypeRef::AbiType(AbiBuiltin::StringView)));
    if any_string_view {
        out.push_str(
            "        // SAFETY: self.host was captured from a valid HostApi in `from_host`\n\
             \x20       // and stays valid for the runtime's lifetime.\n\
             \x20       let host_ctx: HostContext = unsafe { HostContext::new(self.host) };\n",
        );
    }

    if func.params.len() == 1 {
        let param: &ResolvedParam = &func.params[0];
        let ty_name: String = guest_param_type_name(&param.ty);
        match &param.ty {
            ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => {
                out.push_str(&format!(
                    "        let {name}_view: StringView = host_ctx.alloc_string(&{name}).unwrap_or_else(|_| string_view_null());\n",
                    name = param.name
                ));
                out.push_str(&format!(
                    "        let args_ptr: *const () = &{name}_view as *const StringView as *const ();\n",
                    name = param.name
                ));
            }
            ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => {
                out.push_str(&format!(
                    "        let {name}_buf: Buffer = Buffer {{ ptr: {name}.as_mut_ptr(), len: {name}.len(), cap: {name}.capacity() }};\n",
                    name = param.name
                ));
                out.push_str(&format!(
                    "        let args_ptr: *const () = &{name}_buf as *const Buffer as *const ();\n",
                    name = param.name
                ));
            }
            ResolvedTypeRef::UserDefined(_) => {
                // The parameter is received BY VALUE (guest_param_type_name maps
                // UserDefined to the bare type), so take the address of the local
                // — `{name} as *const {ty}` on a by-value enum/struct is an
                // invalid cast (E0606) and never compiled.
                out.push_str(&format!(
                    "        let args_ptr: *const () = &{name} as *const {ty} as *const ();\n",
                    name = param.name,
                    ty = ty_name
                ));
            }
            _ => {
                out.push_str(&format!(
                    "        let {name}_val: {ty} = {name};\n",
                    name = param.name,
                    ty = ty_name
                ));
                out.push_str(&format!(
                    "        let args_ptr: *const () = &{name}_val as *const {ty} as *const ();\n",
                    name = param.name,
                    ty = ty_name
                ));
            }
        }
        return;
    }

    // Multiple params: pack into arg-pack struct
    // Use the same naming convention as arg_pack_struct_name: ContractStruct + FnPascal + Args
    // caller_name is "HostLoggerCaller", we need "HostLogger" (trait name)
    let trait_name: &str = caller_name.strip_suffix("Caller").unwrap_or(caller_name);
    let pack_struct: String = arg_pack_struct_name(trait_name, &func.name);
    out.push_str(&format!(
        "        let args_val: {pack_struct} = {pack_struct} {{\n"
    ));
    for param in &func.params {
        match &param.ty {
            ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => {
                out.push_str(&format!(
                    "            {}: host_ctx.alloc_string(&{}).unwrap_or_else(|_| string_view_null()),\n",
                    param.name, param.name
                ));
            }
            ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => {
                out.push_str(&format!(
                    "            {}: Buffer {{ ptr: {}.as_mut_ptr(), len: {}.len(), cap: {}.capacity() }},\n",
                    param.name, param.name, param.name, param.name
                ));
            }
            _ => {
                out.push_str(&format!("            {},\n", param.name));
            }
        }
    }
    out.push_str("        };\n");
    out.push_str(&format!(
        "        let args_ptr: *const () = &args_val as *const {pack_struct} as *const ();\n"
    ));
}

/// Emit the out_val setup for a guest host contract method.
fn emit_guest_host_contract_out_setup(out: &mut String, returns: &Option<ResolvedTypeRef>) {
    if let Some(ret_ty) = returns {
        let ty_name: String = rust_type_name(ret_ty);
        // MaybeUninit, not zeroed: a zeroed enum discriminant is UB for any
        // contract enum without a `0` variant. The dispatch fills the slot
        // through `out_ptr`; the caller `assume_init`s only after the success
        // check (see `emit_out_assume_init`).
        out.push_str(&format!(
            "        let mut out_val: core::mem::MaybeUninit<{ty_name}> = core::mem::MaybeUninit::uninit();\n"
        ));
        out.push_str("        let out_ptr: *mut () = out_val.as_mut_ptr() as *mut ();\n");
    } else {
        out.push_str("        let out_ptr: *mut () = core::ptr::null_mut();\n");
    }
}

// Suppress unused import warning
const _: fn() = || {
    let _: String = rust_type_name(&ResolvedTypeRef::Primitive(PrimitiveType::U8));
};

/// Generate the full `guest/peer_callers.rs` file for all peer contracts.
fn generate_peer_callers_file(ir: &ValidatedIr, peers: &[&ResolvedContract]) -> String {
    let header: &str = "// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n\
// Re-generate with: polyplugc generate --bundle bundle.toml --lang rust --out <dir>\n\
#![allow(unused_imports)]\n\
#![allow(dead_code)]\n#![allow(non_snake_case)]\n#![allow(non_camel_case_types)]\n#![allow(clippy::all)]\n#![allow(clippy::pedantic)]\n#![allow(clippy::nursery)]\n\n";

    let mut out: String = String::new();
    out.push_str(header);

    // Peer dispatch goes directly through the cached interface (emit_native_vm_dispatch),
    // matching on the interface's dispatch kind — same as the host→guest caller.
    // CallArena is imported only when a peer contract needs the arena (returns
    // StringView/Buffer/UserDefined).
    let any_needs_arena: bool = peers
        .iter()
        .any(|c: &&ResolvedContract| contract_needs_arena(c));
    let mut external: Vec<&str> = vec![
        "polyplug_abi::HostApi",
        "polyplug_abi::GuestContractHandle",
        "polyplug_abi::GuestContractInterface",
        "polyplug_abi::GuestContractInstance",
        "polyplug_abi::StringView",
        "polyplug_abi::AbiError",
        "polyplug_abi::AbiErrorCode",
        "polyplug_abi::DispatchType",
    ];
    if any_needs_arena {
        external.push("polyplug_abi::CallArena");
    }
    out.push_str(&rust_use_block(&[
        &["core::ffi::c_void"],
        &external,
        &["super::types::*"],
    ]));
    out.push('\n');

    if any_needs_arena {
        // Same constant the host_callers file uses — kept in sync here so peer_callers.rs
        // is self-contained and does not depend on host_callers being in scope.
        out.push_str("const CALL_ARENA_BUF_LEN: usize = 512;\n\n");
    }

    out.push_str("/// Error returned from peer guest contract calls.\n");
    out.push_str("#[derive(Debug)]\n");
    out.push_str("pub struct PeerCallError {\n");
    out.push_str("    /// ABI error code (non-zero).\n");
    out.push_str("    pub code: AbiErrorCode,\n");
    out.push_str("    /// Human-readable error message (may be empty).\n");
    out.push_str("    pub message: String,\n");
    out.push_str("}\n\n");
    out.push_str("impl PeerCallError {\n");
    out.push_str("    /// Create a new error with the given code and no message.\n");
    out.push_str("    pub fn new(code: AbiErrorCode) -> Self {\n");
    out.push_str("        Self { code, message: String::new() }\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");

    for contract in peers {
        let min_ver: u32 = peer_min_version(ir, contract.contract_id);
        generate_peer_caller(&mut out, contract, min_ver);
    }

    out
}

/// Generate one `…Peer` struct for a single peer contract.
fn generate_peer_caller(out: &mut String, contract: &ResolvedContract, min_version: u32) {
    let struct_name: String = format!("{}Peer", contract_name_to_struct(&contract.name));
    let needs_arena: bool = contract_needs_arena(contract);

    out.push_str(&format!(
        "/// Peer caller for guest contract `{}` (id=0x{:016X})\n",
        contract.name, contract.contract_id
    ));
    out.push_str("///\n");
    out.push_str(
        "/// Dispatches directly through the cached peer interface — the same near-bare-metal\n\
         /// path as the host→guest caller (no per-call registry resolve, no epoch pin).\n\
         /// The declared dependency keeps the\n\
         /// peer alive (its unload is refused while we are loaded); a hot-reload is caught by\n\
         /// the cached revision counter, which re-resolves before the next dispatch.\n",
    );
    if needs_arena {
        out.push_str("///\n");
        out.push_str(
            "/// # Call-arena lifetime\n\
             ///\n\
             /// Methods returning variable-size values (`StringView`, `Buffer`, or structs\n\
             /// that may embed one) take `&mut self` and reset this caller's arena at the\n\
             /// start of the call. Any view returned by such a method borrows arena memory\n\
             /// and is valid only until the next arena-backed call on the same caller.\n",
        );
    }
    out.push_str(&format!("pub struct {struct_name} {{\n"));
    out.push_str("    /// Resolved interface pointer for the peer contract.\n");
    out.push_str("    interface: *const GuestContractInterface,\n");
    out.push_str("    /// Instance handle created from the peer interface.\n");
    out.push_str("    /// A null `instance.data` is valid for stateless contracts.\n");
    out.push_str("    instance: GuestContractInstance,\n");
    out.push_str(
        "    /// Host interface pointer used to resolve the peer and for instance lifecycle\n\
         \x20   /// (create/destroy) — NOT for dispatch, which goes straight through `interface`.\n",
    );
    out.push_str("    host: *const HostApi,\n");
    out.push_str(
        "    /// Peer contract handle, retained so the cache can re-resolve after a hot-reload\n",
    );
    out.push_str(
        "    /// (which swaps a new interface into the same slot) or report a gone contract.\n",
    );
    out.push_str("    handle: GuestContractHandle,\n");
    out.push_str(
        "    /// Revision value read when the peer was resolved. Compared before each dispatch\n",
    );
    out.push_str(
        "    /// against the live counter to detect a reload/unload and re-resolve, so the cached\n",
    );
    out.push_str("    /// interface pointer and instance never dangle.\n");
    out.push_str("    cached_revision: u64,\n");
    if needs_arena {
        out.push_str(
            "    /// Stable-address backing buffer for the per-call arena. Boxed so the\n\
             \x20   /// arena's interior pointers stay valid when the caller is moved.\n",
        );
        out.push_str("    arena_buf: Box<[u8; CALL_ARENA_BUF_LEN]>,\n");
        out.push_str(
            "    /// Per-call bump arena over `arena_buf`, reset at each arena-backed call.\n",
        );
        out.push_str("    arena: CallArena,\n");
    }
    out.push_str("}\n\n");

    out.push_str(&format!("impl {struct_name} {{\n"));

    // resolve()
    out.push_str("    /// Discover and resolve the peer contract through the host.\n");
    out.push_str("    ///\n");
    out.push_str("    /// `host` is the per-instance context handed to the author factory\n");
    out.push_str("    /// (`polyplug_create_<plugin>`) — no process-wide host storage exists.\n");
    out.push_str("    ///\n");
    out.push_str(
        "    /// Returns `None` if the host context is null, the contract is not found,\n",
    );
    out.push_str("    /// or the resolved interface pointer is null.\n");
    out.push_str("    pub fn resolve(host: polyplug_guest::HostContext) -> Option<Self> {\n");
    out.push_str("        let host: *const HostApi = host.as_ptr();\n");
    out.push_str(
        "        // SAFETY: host is checked for null via as_ref() which returns None on null.\n",
    );
    out.push_str("        let iface_api: &HostApi = unsafe { host.as_ref()? };\n");
    out.push_str("        // SAFETY: iface_api is the reborrowed non-null HostApi; find_guest_contract is an\n");
    out.push_str("        // ABI function pointer safe to call with a valid host (returns a zero handle if absent).\n");
    out.push_str(&format!(
        "        let handle: GuestContractHandle = unsafe {{\n\
         \x20           (iface_api.find_guest_contract)(host, 0x{:016X}_u64, {min_version}_u32)\n\
         \x20       }};\n",
        contract.contract_id
    ));
    out.push_str("        // SAFETY: handle is the value returned by find_guest_contract; resolve_guest_contract\n");
    out.push_str(
        "        // is safe to call with any handle (returns null for stale/invalid handles).\n",
    );
    out.push_str("        let interface: *const GuestContractInterface = unsafe {\n");
    out.push_str("            (iface_api.resolve_guest_contract)(host, handle)\n");
    out.push_str("        };\n");
    out.push_str("        if interface.is_null() {\n");
    out.push_str("            return None;\n");
    out.push_str("        }\n");
    out.push_str("        // A null instance.data is valid: stateless contracts return a null\n");
    out.push_str(
        "        // handle from create_instance and use it as an opaque dispatch token.\n",
    );
    out.push_str(
        "        // Route creation through the host so the runtime tracks the instance.\n",
    );
    out.push_str(
        "        let mut instance: GuestContractInstance = GuestContractInstance::null();\n",
    );
    out.push_str(
        "        // SAFETY: interface is non-null (checked above) and points to a valid\n",
    );
    out.push_str("        // GuestContractInterface produced by resolve_guest_contract.\n");
    out.push_str("        unsafe {\n");
    out.push_str(
        "            (iface_api.create_guest_instance)(host, interface, core::ptr::null(), &mut instance);\n",
    );
    out.push_str("        };\n");
    out.push_str(
        "        // Capture the acquire-synchronized registry revision value for this resolved\n",
    );
    out.push_str(
        "        // peer interface. Each later dispatch invokes the same HostApi callback before use.\n",
    );
    out.push_str(
        "        // SAFETY: iface_api is the reborrowed non-null HostApi and registry_revision\n",
    );
    out.push_str("        // is an ABI function pointer safe to call with a valid host.\n");
    out.push_str(
        "        let cached_revision: u64 = unsafe { (iface_api.registry_revision)(host) };\n",
    );
    if needs_arena {
        out.push_str(
            "        // Box the backing buffer first so the arena's interior pointers refer\n",
        );
        out.push_str(
            "        // to a stable heap address that survives moving the caller value.\n",
        );
        out.push_str("        let mut arena_buf: Box<[u8; CALL_ARENA_BUF_LEN]> = Box::new([0u8; CALL_ARENA_BUF_LEN]);\n");
        out.push_str(
            "        let arena: CallArena = CallArena::new(arena_buf.as_mut_slice(), host);\n",
        );
        out.push_str(&format!(
            "        Some({struct_name} {{ interface, instance, host, handle, cached_revision, arena_buf, arena }})\n"
        ));
    } else {
        out.push_str(&format!(
            "        Some({struct_name} {{ interface, instance, host, handle, cached_revision }})\n"
        ));
    }
    out.push_str("    }\n\n");

    // live_revision()
    out.push_str("    /// Read the synchronized registry revision through HostApi.\n");
    out.push_str("    #[inline]\n");
    out.push_str("    fn live_revision(&self) -> u64 {\n");
    out.push_str("        // SAFETY: self.host is retained for the caller lifetime.\n");
    out.push_str("        let host_api: &HostApi = unsafe { &*self.host };\n");
    out.push_str("        // SAFETY: registry_revision is safe to call with the live host.\n");
    out.push_str("        unsafe { (host_api.registry_revision)(self.host) }\n");
    out.push_str("    }\n\n");

    // is_valid()
    out.push_str("    /// Returns `true` if this peer holds a resolved (non-null) interface.\n");
    out.push_str("    pub fn is_valid(&self) -> bool {\n");
    out.push_str("        !self.interface.is_null()\n");
    out.push_str("    }\n\n");

    // revalidate()
    out.push_str(
        "    /// Re-resolve the cached peer interface after the registry changed under us.\n",
    );
    out.push_str("    ///\n");
    out.push_str("    /// Invoked automatically when a dispatch observes a revision change. A\n");
    out.push_str(
        "    /// hot-reload swapped a new interface into the same slot, so the retained\n",
    );
    out.push_str(
        "    /// handle still resolves — to the new interface; an unload vacated the slot,\n",
    );
    out.push_str("    /// so it resolves to null and `false` is returned (the peer is gone).\n");
    out.push_str("    ///\n");
    out.push_str("    /// The old instance is ABANDONED, never destroyed: after a reload its\n");
    out.push_str(
        "    /// interface — and the guest-side state it created — is already epoch-reclaimed,\n",
    );
    out.push_str("    /// so calling the dead interface's `destroy_instance` would be undefined\n");
    out.push_str(
        "    /// behaviour. The runtime reclaims the old instance's backing as part of the\n",
    );
    out.push_str("    /// reload, then a fresh instance is created on the new interface.\n");
    out.push_str("    fn revalidate(&mut self) -> bool {\n");
    out.push_str("        // SAFETY: self.host is the stored host pointer; as_ref() returns None when it is null.\n");
    out.push_str("        let iface_api: &HostApi = match unsafe { self.host.as_ref() } {\n");
    out.push_str("            Some(api) => api,\n");
    out.push_str("            None => return false,\n");
    out.push_str("        };\n");
    out.push_str("        // SAFETY: resolve_guest_contract is an ABI fn ptr safe to call with a valid host and handle.\n");
    out.push_str("        let interface: *const GuestContractInterface =\n");
    out.push_str(
        "            unsafe { (iface_api.resolve_guest_contract)(self.host, self.handle) };\n",
    );
    out.push_str("        if interface.is_null() {\n");
    out.push_str("            return false;\n");
    out.push_str("        }\n");
    out.push_str(
        "        let mut instance: GuestContractInstance = GuestContractInstance::null();\n",
    );
    out.push_str("        // SAFETY: interface is freshly resolved and valid; create_guest_instance writes the new instance.\n");
    out.push_str("        unsafe {\n");
    out.push_str(
        "            (iface_api.create_guest_instance)(self.host, interface, core::ptr::null(), &mut instance);\n",
    );
    out.push_str("        }\n");
    out.push_str("        self.instance = instance;\n");
    out.push_str("        self.interface = interface;\n");
    out.push_str("        self.cached_revision = self.live_revision();\n");
    out.push_str("        true\n");
    out.push_str("    }\n\n");

    // Methods
    for func in &contract.functions {
        generate_peer_fn_caller(out, func, &struct_name);
    }

    out.push_str("}\n\n");

    // Drop impl
    out.push_str(&format!("impl Drop for {struct_name} {{\n"));
    out.push_str("    fn drop(&mut self) {\n");
    if needs_arena {
        out.push_str(
            "        // Free any overflow blocks the arena still holds before dropping.\n",
        );
        out.push_str("        self.arena.reset();\n");
    }
    out.push_str(
        "        // Route destruction through the host so the runtime drops the instance from\n",
    );
    out.push_str(
        "        // its live-instance accounting. A null host pointer means there is no\n",
    );
    out.push_str("        // runtime to mediate the lifecycle, so skip the destroy.\n");
    out.push_str("        // SAFETY: self.host is the stored host pointer; as_ref() returns None when it is\n");
    out.push_str("        // null, so the borrow only occurs for a valid HostApi.\n");
    out.push_str("        let host_api: &HostApi = match unsafe { self.host.as_ref() } {\n");
    out.push_str("            Some(api) => api,\n");
    out.push_str("            None => return,\n");
    out.push_str("        };\n");
    out.push_str(
        "        // If the registry changed since we resolved, the cached interface and instance\n",
    );
    out.push_str(
        "        // are stale — a reload/unload reclaimed their backing — so calling the dead\n",
    );
    out.push_str(
        "        // interface's destroy would be UB; the reload/unload already reclaimed the\n",
    );
    out.push_str("        // instance, so skip the destroy entirely.\n");
    out.push_str("        if self.live_revision() != self.cached_revision {\n");
    out.push_str("            return;\n");
    out.push_str("        }\n");
    out.push_str("        // We guard on instance.data to skip the call for stateless (null-data) contracts.\n");
    out.push_str("        if !self.instance.data.is_null() {\n");
    out.push_str(
        "            // SAFETY: instance was created by create_guest_instance on the resolved interface.\n",
    );
    out.push_str("            // The interface pointer is stored for the lifetime of this wrapper and is valid.\n");
    out.push_str("            unsafe {\n");
    out.push_str(
        "                (host_api.destroy_guest_instance)(self.host, self.interface, self.instance);\n",
    );
    out.push_str("            }\n");
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");
}

/// Generate one caller method for a peer contract function.
///
/// Dispatches directly through the cached interface via `emit_native_vm_dispatch` —
/// the same mechanism `generate_host_fn_caller` uses. Parameters and return types use `rust_type_name`
/// (raw ABI types: StringView, Buffer, primitives) so the `out_val` buffer is
/// correctly sized and the host never writes past it. When the return type is
/// variable-size (`fn_needs_arena`), the method takes `&mut self`, resets the
/// arena, and passes `&mut self.arena` so the peer can write into it.
fn generate_peer_fn_caller(out: &mut String, func: &ResolvedFunction, struct_name: &str) {
    let fn_id: u32 = func.function_id;
    let needs_arena: bool = fn_needs_arena(func);

    // Use the same sig-param builder as the host caller (rust_type_name-based).
    let sig_params: String = build_sig_params(func);

    let ret_type: String = match &func.returns {
        Some(ty) => rust_type_name(ty),
        None => "()".to_owned(),
    };

    out.push_str(&format!(
        "    /// Call peer function `{}` (function_id={}) via direct cached-interface dispatch.\n",
        func.name, fn_id
    ));
    out.push_str("    #[allow(clippy::absurd_extreme_comparisons)]\n");
    // All methods take `&mut self`: the per-call staleness check may invoke
    // revalidate(), which re-resolves the interface and recreates the instance.
    let self_param: &str = "&mut self";
    if needs_arena {
        out.push_str(
            "    /// Returns a value borrowing this caller's arena; it stays valid until\n\
             \x20   /// the next arena-backed call on this caller.\n",
        );
    }
    out.push_str(&format!(
        "    pub fn {}({self_param}{sig_params}) -> Result<{ret_type}, PeerCallError> {{\n",
        func.name
    ));

    // Per-call staleness check: re-resolve if the registry changed under us.
    out.push_str(
        "        // Compare the current acquire-synchronized registry revision before using\n",
    );
    out.push_str(
        "        // the cached peer interface. A change re-resolves before direct dispatch,\n",
    );
    out.push_str("        // so a reclaimed interface and instance are never used.\n");
    out.push_str(
        "        if self.live_revision() != self.cached_revision && !self.revalidate() {\n",
    );
    out.push_str("            return Err(PeerCallError::new(AbiErrorCode::NotFound));\n");
    out.push_str("        }\n");

    if needs_arena {
        out.push_str(
            "        // Reset the arena at call start: frees the previous call's overflow\n",
        );
        out.push_str(
            "        // blocks and rewinds the primary region, invalidating prior views.\n",
        );
        out.push_str("        self.arena.reset();\n");
    }

    // args_ptr setup — identical helpers to the host caller (rust_type_name-based).
    emit_args_setup(out, func, struct_name);

    // out_val / out_ptr setup — uses rust_type_name so the buffer is correctly sized.
    emit_out_setup(out, &func.returns);

    let param_ty_comment: String = args_type_comment(func, struct_name);
    let ret_ty_comment: String = ret_type.clone();
    out.push_str(&format!(
        "        // SAFETY: args_ptr points to a valid {param_ty_comment} and out_ptr to a valid {ret_ty_comment}.\n"
    ));
    out.push_str("        // Enforced by the generated caller contract.\n");
    out.push_str("        let out_ptr: *mut () = ");
    if func.returns.is_some() {
        out.push_str("out_val.as_mut_ptr() as *mut ();\n");
    } else {
        out.push_str("core::ptr::null_mut();\n");
    }
    // Dispatch directly through the cached peer interface — the SAME near-bare-metal
    // path the host→guest caller uses (emit_native_vm_dispatch). No host-mediated
    // call_guest_method round-trip, no per-call registry resolve, no epoch pin: the
    // declared dependency keeps the peer's interface alive (its unload is refused
    // while we are loaded), and a reload is caught by the revision check above, which
    // re-resolves before we reach here.
    emit_native_vm_dispatch(out, fn_id, needs_arena);

    // Error handling — identical to host caller.
    out.push_str("        if err.code != AbiErrorCode::Ok as u32 {\n");
    out.push_str("            let message: String = if err.message.ptr.is_null() || err.message.len == 0 {\n");
    out.push_str("                String::new()\n");
    out.push_str("            } else {\n");
    out.push_str("                // SAFETY: err.message.ptr is valid for err.message.len bytes and points to UTF-8 data.\n");
    out.push_str(
        "                // The message is owned by the producer (static or runtime-owned); the\n",
    );
    out.push_str(
        "                // receiver must NEVER free it. We only copy it into an owned String.\n",
    );
    out.push_str("                let s: String = unsafe {\n");
    out.push_str("                    let slice: &[u8] = core::slice::from_raw_parts(err.message.ptr, err.message.len);\n");
    out.push_str("                    core::str::from_utf8_unchecked(slice).to_owned()\n");
    out.push_str("                };\n");
    out.push_str("                s\n");
    out.push_str("            };\n");
    out.push_str(
        "            return Err(PeerCallError { code: AbiErrorCode::from_u32(err.code), message });\n",
    );
    out.push_str("        }\n");

    // Return
    if func.returns.is_some() {
        emit_out_assume_init(out, &func.returns);
        out.push_str("        Ok(out_val)\n");
    } else {
        out.push_str("        Ok(())\n");
    }

    out.push_str("    }\n\n");
}

fn generate_guest_mod_rs(ir: &ValidatedIr) -> String {
    let mut out: String = String::new();
    out.push_str(RUST_FILE_HEADER);
    out.push_str("pub mod contracts;\n");
    out.push_str("pub mod init;\n");
    out.push_str("pub mod types;\n");
    out.push_str("pub mod interfaces;\n");
    if !ir.host_contracts.is_empty() {
        out.push_str("pub mod host_contract_callers;\n");
    }
    let peer_contracts: Vec<&ResolvedContract> = collect_peer_contracts(ir);
    if !peer_contracts.is_empty() {
        out.push_str("pub mod peer_callers;\n");
    }
    out
}

