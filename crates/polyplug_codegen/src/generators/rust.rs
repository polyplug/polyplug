fn generate_rust_type(
    out: &mut String,
    ty: &ResolvedType,
    types: &[ResolvedType],
    enums: &[EnumDef],
) -> Result<(), PolyplugcError> {
    let mut docs: Vec<String> = vec![format!("User-defined type `{}`", ty.name)];
    append_lines(&mut docs, ty.docs.as_deref());
    let fields: Vec<(String, String, Option<String>)> = ty
        .fields
        .iter()
        .map(|f: &ResolvedField| (f.name.clone(), rust_type_name(&f.ty), f.docs.clone()))
        .collect::<Vec<(String, String, Option<String>)>>();
    // A struct is `Copy`/`Clone` only if every field is. `Buffer` is an owning
    // type (host-freed, single-owner) that is deliberately NOT `Copy`, so a struct
    // embedding one (directly or transitively) derives only `Debug` — copying its
    // owned pointer would alias ownership.
    let copyable: bool = ty
        .fields
        .iter()
        .all(|f: &ResolvedField| rust_type_ref_is_copy(&f.ty, types, enums));
    out.push_str(&render_rust_repr_c_struct(
        &ty.name, docs, fields, copyable,
    )?);
    // Array wrappers (`ArrayOf_T`, from desugaring `Array<T>`) get a typed
    // read accessor so the host reads their `items`/`len` back as a `&[T]`
    // instead of reinterpreting a raw pointer at each call site.
    if let Some(element) = array_element_name(&ty.name) {
        emit_array_wrapper_as_slice(out, &ty.name, element);
    }
    Ok(())
}

/// Whether a value of `ty` is `Copy` (and thus `Clone`) in generated Rust. Every
/// ABI value type is `Copy` except `Buffer` (owning), and a user struct is `Copy`
/// only if all its fields are. Enums generate as `Copy` C-like enums; array
/// wrappers are two `u64`s.
fn rust_type_ref_is_copy(ty: &ResolvedTypeRef, types: &[ResolvedType], enums: &[EnumDef]) -> bool {
    match ty {
        ResolvedTypeRef::Primitive(_) => true,
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => false,
        ResolvedTypeRef::AbiType(_) => true,
        ResolvedTypeRef::UserDefined(name) => {
            if array_element_name(name).is_some() || enums.iter().any(|e: &EnumDef| &e.name == name)
            {
                return true;
            }
            match types.iter().find(|t: &&ResolvedType| &t.name == name) {
                Some(s) => s
                    .fields
                    .iter()
                    .all(|f: &ResolvedField| rust_type_ref_is_copy(&f.ty, types, enums)),
                None => true,
            }
        }
    }
}

/// Emit `impl ArrayOf_T { unsafe fn as_slice(&self) -> &[T] }` for an array
/// wrapper struct. The element bytes live in the producing guest's return buffer
/// (or the caller's arena), so the borrow is tied to that memory's lifetime, not
/// to the 16-byte wrapper — hence `unsafe` with the valid-until-next-call rule.
fn emit_array_wrapper_as_slice(out: &mut String, wrapper: &str, element: &str) {
    out.push_str(&format!("impl {wrapper} {{\n"));
    out.push_str(&format!(
        "    /// Borrow this array's elements as `&[{element}]`.\n"
    ));
    out.push_str("    ///\n");
    out.push_str("    /// # Safety\n");
    out.push_str(&format!(
        "    /// `items` must point at `len` initialized `{element}` values produced by\n"
    ));
    out.push_str("    /// a guest return; the slice is valid only until the next arena-backed\n");
    out.push_str("    /// call on the caller that produced it. Copy out before the next call.\n");
    out.push_str(&format!(
        "    pub unsafe fn as_slice<'a>(&self) -> &'a [{element}] {{\n"
    ));
    out.push_str("        if self.items == 0 || self.len == 0 {\n");
    out.push_str("            return &[];\n");
    out.push_str("        }\n");
    out.push_str(&format!(
        "        // SAFETY: the caller guarantees `items` points at `len` valid `{element}`\n"
    ));
    out.push_str("        // values for the borrow's lifetime (see the method contract above).\n");
    out.push_str(&format!(
        "        unsafe {{ core::slice::from_raw_parts(self.items as *const {element}, self.len as usize) }}\n"
    ));
    out.push_str("    }\n");
    out.push_str("}\n\n");
}

fn rust_type_name(ty: &ResolvedTypeRef) -> String {
    match ty {
        ResolvedTypeRef::Primitive(p) => p.rust_name().to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => "StringView".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => "Buffer".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Ptr) => "*mut ()".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Void) => "()".to_owned(),
        ResolvedTypeRef::UserDefined(name) => name.clone(),
    }
}

fn to_snake_case(s: &str) -> String {
    let mut result: String = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            result.push('_');
        }
        result.extend(c.to_lowercase());
    }
    result
}

fn substitute_variant_refs_rust_enum(
    declared_variants: &[EnumVariant],
    expr: &str,
    _enum_name: &str,
    repr_type: &str,
) -> String {
    let declared_names: Vec<&str> = declared_variants.iter().map(|v| v.name.as_str()).collect();
    let chars: Vec<char> = expr.chars().collect();
    let len: usize = chars.len();
    let mut result: String = String::new();
    let mut i: usize = 0;
    while i < len {
        let c: char = chars[i];
        if c.is_alphabetic() || c == '_' {
            let start: usize = i;
            while i < len && (chars[i].is_alphanumeric() || chars[i] == '_') {
                i += 1;
            }
            let ident: String = chars[start..i].iter().collect();
            if declared_names.contains(&ident.as_str()) {
                result.push_str(&format!("Self::{} as {}", ident, repr_type));
            } else {
                result.push_str(&ident);
            }
        } else {
            result.push(c);
            i += 1;
        }
    }
    result
}

fn substitute_variant_refs_rust_bitflag(declared_variants: &[EnumVariant], expr: &str) -> String {
    let declared_names: Vec<&str> = declared_variants.iter().map(|v| v.name.as_str()).collect();
    let chars: Vec<char> = expr.chars().collect();
    let len: usize = chars.len();
    let mut result: String = String::new();
    let mut i: usize = 0;
    while i < len {
        let c: char = chars[i];
        if c.is_alphabetic() || c == '_' {
            let start: usize = i;
            while i < len && (chars[i].is_alphanumeric() || chars[i] == '_') {
                i += 1;
            }
            let ident: String = chars[start..i].iter().collect();
            if declared_names.contains(&ident.as_str()) {
                result.push_str(&ident.to_uppercase());
            } else {
                result.push_str(&ident);
            }
        } else {
            result.push(c);
            i += 1;
        }
    }
    result
}

fn generate_rust_enum(out: &mut String, e: &EnumDef) -> Result<(), PolyplugcError> {
    let repr_str: &str = e.repr.rust_name();
    if e.bitflag {
        let mod_name: String = to_snake_case(&e.name);
        out.push_str(&format!(
            "/// Bitflag enum `{}` (repr {})\n",
            e.name, repr_str
        ));
        for line in super::docs::lines(e.docs.as_deref()) {
            out.push_str(&format!("/// {line}\n"));
        }
        out.push_str(&format!("pub mod {} {{\n", mod_name));
        out.push_str(&format!("    pub type {} = {};\n", e.name, repr_str));
        for variant in &e.variants {
            let subst_value: String =
                substitute_variant_refs_rust_bitflag(&e.variants, &variant.value);
            for line in super::docs::lines(variant.docs.as_deref()) {
                out.push_str(&format!("    /// {line}\n"));
            }
            out.push_str(&format!(
                "    pub const {}: {} = {};\n",
                variant.name.to_uppercase(),
                e.name,
                subst_value
            ));
        }
        out.push_str("}\n");
        out.push_str(&format!("pub use {}::{};\n\n", mod_name, e.name));
    } else {
        out.push_str(&render_rust_enum_decl(e, repr_str)?);
    }
    Ok(())
}

/// Render a `#[repr(_)] #[derive(...)] pub enum` (the non-bitflag path) via
/// langprint's Rust EnumRenderer. `attributes_before_derives` reproduces
/// polyplugc's `#[repr(_)]`-first order; rustfmt canonicalizes the rest.
fn render_rust_enum_decl(e: &EnumDef, repr_str: &str) -> Result<String, PolyplugcError> {
    let variants: Vec<RustEnumVariant> = e
        .variants
        .iter()
        .map(|variant: &EnumVariant| {
            let subst_value: String =
                substitute_variant_refs_rust_enum(&e.variants, &variant.value, &e.name, repr_str);
            RustEnumVariant {
                name: variant.name.clone(),
                value: RustEnumVariantValue::Discriminant(subst_value),
                docs: variant.docs.as_ref().map(|docs| {
                    let mut lines: Vec<String> = Vec::new();
                    append_lines(&mut lines, Some(docs));
                    lines
                }),
            }
        })
        .collect::<Vec<RustEnumVariant>>();
    let rust_enum: RustEnum = RustEnum {
        name: e.name.clone(),
        visibility: RustVisibility::Pub,
        variants,
        repr: Some(repr_str.to_owned()),
        derives: vec![
            "Debug".to_owned(),
            "Clone".to_owned(),
            "Copy".to_owned(),
            "PartialEq".to_owned(),
            "Eq".to_owned(),
        ],
        docs: {
            let mut docs: Vec<String> = vec![format!("Enum `{}` (repr {})", e.name, repr_str)];
            append_lines(&mut docs, e.docs.as_deref());
            Some(docs)
        },
    };
    let options: RustEnumRenderOptions = RustEnumRenderOptions {
        attributes_before_derives: true,
        ..RustEnumRenderOptions::default()
    };
    let backend: RustBackend = RustBackend::default();
    let mut indent_level: i32 = 0;
    let rendered: String = backend
        .render_enum(
            &rust_enum,
            None::<&str>,
            None::<&str>,
            Some(&options),
            &mut indent_level,
        )
        .map_err(|source: io::Error| PolyplugcError::WriteFailed {
            path: "guest/types.rs".to_owned(),
            source,
        })?;
    Ok(format!("{rendered}\n"))
}

fn contract_name_to_struct(name: &str) -> String {
    // Convert "image.decode" -> "ImageDecodeContract"
    name.split('.')
        .map(|p: &str| {
            let mut chars: core::str::Chars<'_> = p.chars();
            match chars.next() {
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join("")
        + "Contract"
}

/// Convert host contract name to trait name.
/// e.g. "host.logger" -> "HostLogger", "host.fs.reader" -> "HostFsReader"
fn host_contract_name_to_trait(name: &str) -> String {
    let name_without_prefix: &str = name.strip_prefix("host.").unwrap_or(name);

    let pascal: String = name_without_prefix
        .split('.')
        .map(|p: &str| {
            let mut chars: core::str::Chars<'_> = p.chars();
            match chars.next() {
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join("");

    if pascal.starts_with("Host") {
        pascal
    } else {
        "Host".to_owned() + &pascal
    }
}

/// Convert host contract name to guest caller struct name.
/// e.g. "host.logger" -> "HostLoggerCaller", "host.fs.reader" -> "HostFsReaderCaller"
fn host_contract_name_to_caller(name: &str) -> String {
    host_contract_name_to_trait(name) + "Caller"
}

/// Generate ergonomic host-side type name for trait method parameters.
/// For host traits, we use borrowed types where appropriate:
/// - StringView -> &str (more ergonomic for host implementers)
/// - Buffer -> &[u8] (more ergonomic for host implementers)
/// - UserDefined -> &TypeName (passed by reference)
/// - Primitives -> T (passed by value)
fn host_param_type_name(ty: &ResolvedTypeRef) -> String {
    match ty {
        ResolvedTypeRef::Primitive(p) => p.rust_name().to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => "&str".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => "&[u8]".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Ptr) => "*mut ()".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Void) => "()".to_owned(),
        ResolvedTypeRef::UserDefined(name) => format!("&{name}"),
    }
}

/// Generate host-side return type name for trait methods.
/// Return types are owned where appropriate:
/// - StringView -> String (owned)
/// - Buffer -> Vec<u8> (owned)
/// - UserDefined -> TypeName (owned, caller must copy)
/// - Primitives -> T (by value)
fn host_return_type_name(ty: &ResolvedTypeRef) -> String {
    match ty {
        ResolvedTypeRef::Primitive(p) => p.rust_name().to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => "String".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => "Vec<u8>".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Ptr) => "*mut ()".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Void) => "()".to_owned(),
        ResolvedTypeRef::UserDefined(name) => name.clone(),
    }
}

/// Generate the trait definition for one host contract.
fn generate_host_contract_trait(out: &mut String, contract: &ResolvedHostContract) {
    let trait_name: String = host_contract_name_to_trait(&contract.name);
    out.push_str(&format!(
        "/// Host trait for contract `{}` (id=0x{:016X})\n",
        contract.name, contract.contract_id
    ));
    out.push_str("/// Hosts implement this trait to provide functionality to plugins.\n");
    for line in super::docs::lines(contract.docs.as_deref()) {
        out.push_str(&format!("/// {line}\n"));
    }
    out.push_str(&format!("pub trait {trait_name}: Send + Sync {{\n"));
    for func in &contract.functions {
        generate_host_trait_method(out, func);
    }
    out.push_str("}\n\n");
}

/// Generate one trait method for a host contract function.
fn generate_host_trait_method(out: &mut String, func: &ResolvedFunction) {
    let params_str: String = if func.params.is_empty() {
        String::new()
    } else {
        func.params
            .iter()
            .map(|p: &ResolvedParam| format!(", {}: {}", p.name, host_param_type_name(&p.ty)))
            .collect::<Vec<_>>()
            .join("")
    };

    let ret_type: String = match &func.returns {
        Some(ty) => host_return_type_name(ty),
        None => "()".to_owned(),
    };

    for line in super::docs::lines(func.docs.as_deref()) {
        out.push_str(&format!("    /// {line}\n"));
    }
    for param in &func.params {
        for line in super::docs::lines(param.docs.as_deref()) {
            out.push_str(&format!(
                "    ///\n    /// # Arguments\n    /// * `{}` — {line}\n",
                param.name
            ));
        }
    }
    for line in super::docs::lines(func.return_docs.as_deref()) {
        out.push_str(&format!("    ///\n    /// # Returns\n    /// {line}\n"));
    }
    out.push_str(&format!(
        "    fn {}(&self{}) -> {ret_type};\n",
        func.name, params_str
    ));
}

