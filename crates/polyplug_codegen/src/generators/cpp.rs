// ─── contracts.hpp generator ─────────────────────────────────────────────────

fn generate_contracts_hpp(ir: &ValidatedIr) -> Result<String, PolyplugcError> {
    let mut out: String = String::new();
    out.push_str(CPP_FILE_HEADER);
    out.push_str("// Re-generate with: polyplugc generate --api api.toml --lang cpp --out <dir>\n");
    out.push_str("#pragma once\n");
    out.push_str(&cpp_include_block(&[
        &[("types.hpp", false)],
        &[("cstdint", true)],
    ]));
    out.push('\n');
    out.push_str("namespace polyplug_plugin {\n\n");
    out.push_str("struct RuntimeError { uint32_t code; };\n\n");

    for contract in &ir.contracts {
        generate_cpp_guest_contract_class(&mut out, contract)?;
    }

    out.push_str("}  // namespace polyplug_plugin\n");
    Ok(out)
}

fn generate_cpp_guest_contract_class(
    out: &mut String,
    contract: &ResolvedContract,
) -> Result<(), PolyplugcError> {
    let class_name: String = contract_name_to_guest_contract_class(&contract.name);
    out.push_str(&format!(
        "/// Abstract plugin base for contract `{}` (id=0x{:016X})\n",
        contract.name, contract.contract_id
    ));
    for line in super::docs::lines(contract.docs.as_deref()) {
        out.push_str(&format!("/// {line}\n"));
    }
    out.push_str(&format!("class {} {{\npublic:\n", class_name));
    out.push_str(&format!("    virtual ~{}() = default;\n", class_name));

    for func in &contract.functions {
        out.push_str(&cpp_render_abstract_method(func)?);
    }

    out.push_str("};\n\n");
    Ok(())
}

/// Render one pure-virtual guest-contract method via langprint (declaration-mode
/// `CppFunction`). Preserves polyplugc's parameter rule: a user-defined param is
/// taken by `const T&`, primitives/ABI types by value.
fn cpp_render_abstract_method(func: &ResolvedFunction) -> Result<String, PolyplugcError> {
    let return_type: String = func
        .returns
        .as_ref()
        .map(cpp_type_name)
        .unwrap_or_else(|| "void".to_owned());

    let parameters: Vec<CppParameter> = func
        .params
        .iter()
        .map(|p: &ResolvedParam| {
            let cpp_ty: String = cpp_type_name(&p.ty);
            let param_type: String = match &p.ty {
                ResolvedTypeRef::UserDefined(_) => format!("const {}&", cpp_ty),
                ResolvedTypeRef::Primitive(_) | ResolvedTypeRef::AbiType(_) => cpp_ty,
            };
            CppParameter {
                name: p.name.clone(),
                param_type,
                default_value: None,
            }
        })
        .collect::<Vec<CppParameter>>();

    let mut docs: Vec<String> = Vec::new();
    append_lines(&mut docs, func.docs.as_deref());
    for param in &func.params {
        if let Some(param_docs) = param.docs.as_deref() {
            docs.push(format!("@param {} {param_docs}", param.name));
        }
    }
    if let Some(return_docs) = func.return_docs.as_deref() {
        docs.push(format!("@return {return_docs}"));
    }
    let method: CppFunction = CppFunction {
        name: func.name.clone(),
        parent_name: None,
        visibility: CppVisibility::Public,
        parameters,
        template_params: Vec::new(),
        return_type: Some(return_type),
        is_static: false,
        is_const: false,
        is_virtual: true,
        is_pure_virtual: true,
        is_inline: false,
        is_noexcept: false,
        is_override: false,
        is_final: false,
        is_extern_c: false,
        is_friend: false,
        is_deleted: false,
        is_default: false,
        body: None,
        docs: (!docs.is_empty()).then_some(docs),
    };
    let backend: CppBackend = CppBackend::default();
    let mut indent_level: i32 = 1;
    let rendered: String = backend
        .render_function(&method, None::<&str>, None::<&str>, None, &mut indent_level)
        .map_err(|source: io::Error| PolyplugcError::WriteFailed {
            path: "guest/contracts.hpp".to_owned(),
            source,
        })?;
    Ok(format!("{rendered}\n"))
}

// ─── interfaces.hpp generator ───────────────────────────────────────────────────

fn generate_interfaces_hpp(ir: &ValidatedIr) -> Result<String, PolyplugcError> {
    let mut out: String = String::new();
    out.push_str(CPP_FILE_HEADER);
    out.push_str("// Re-generate with: polyplugc generate --api api.toml --lang cpp --out <dir>\n");
    out.push_str("#pragma once\n");
    out.push_str(&cpp_include_block(&[
        &[("contracts.hpp", false), ("polyplug/abi.hpp", false)],
        &[("cstdint", true), ("cstring", true), ("exception", true)],
    ]));
    out.push('\n');
    out.push_str("namespace polyplug_plugin {\n\n");

    if let Some(bundle) = &ir.bundle {
        let mut emitted_consts: HashSet<String> = HashSet::new();
        for plugin in &bundle.plugins {
            for contract_impl in &plugin.implements {
                if let Some(contract) = ir.contracts.iter().find(|c| {
                    let contract_full: String =
                        format!("{}@{}.{}", c.name, c.version.major, c.version.minor);
                    &contract_full == contract_impl
                }) {
                    generate_cpp_guest_plugin_interface(
                        &mut out,
                        &plugin.name,
                        contract,
                        is_native_runtime(&bundle.loader),
                        &mut emitted_consts,
                    )?;
                }
            }
        }
    } else {
        // When no bundle info, default to native dispatch
        for contract in &ir.contracts {
            generate_cpp_guest_contract_interface(&mut out, contract, true)?;
        }
    }

    out.push_str("}  // namespace polyplug_plugin\n");
    Ok(out)
}

/// Generate dispatch wrappers for the explicit internal profile.
///
/// Unlike an external guest, provider construction is owned by the generated
/// registrar. These wrappers therefore contain only the shared ABI dispatch
/// machinery; `internal.hpp` supplies the per-provider create/destroy thunks.
fn generate_cpp_internal_interfaces_hpp(ir: &ValidatedIr) -> Result<String, PolyplugcError> {
    let bundle = ir
        .bundle
        .as_ref()
        .ok_or_else(|| PolyplugcError::ValidationFailed {
            message: "C++ internal interfaces require a bundle manifest".to_owned(),
        })?;
    let mut out = String::new();
    out.push_str(CPP_FILE_HEADER);
    out.push_str("#pragma once\n");
    out.push_str(&cpp_include_block(&[
        &[("contracts.hpp", false), ("polyplug/abi.hpp", false)],
        &[("cstdint", true), ("exception", true)],
    ]));
    out.push_str("\nnamespace polyplug_plugin {\n\n");
    let mut emitted_consts = HashSet::new();
    for plugin in &bundle.plugins {
        for contract_impl in &plugin.implements {
            let contract = resolve_cpp_internal_contract(ir, contract_impl)?;
            let symbol = cpp_internal_provider_symbol(&plugin.name, contract);
            let symbol_upper = symbol.to_uppercase();
            let state_struct = format!("{}InstanceState", snake_to_pascal(&symbol));
            let contract_upper = contract_name_to_upper_snake(&contract.name);
            out.push_str(&format!(
                "// Provider: {} -> {}\n",
                plugin.name, contract.name
            ));
            if emitted_consts.insert(contract_upper.clone()) {
                out.push_str(&format!(
                    "constexpr uint64_t {}_CONTRACT_ID = 0x{:016X}ULL;\n\n",
                    contract_upper, contract.contract_id
                ));
            }
            generate_cpp_internal_instance_state(
                &mut out,
                &state_struct,
                &contract_name_to_guest_contract_class(&contract.name),
                &symbol,
            );
            for function in &contract.functions {
                generate_cpp_guest_abi_wrapper(&mut out, &symbol, &state_struct, function)?;
            }
            out.push_str(&format!("static void* const {symbol_upper}_FNS[] = {{\n"));
            for function in &contract.functions {
                out.push_str(&format!(
                    "    reinterpret_cast<void*>({symbol}_{}_abi),\n",
                    function.name
                ));
            }
            out.push_str("};\n\n");
        }
    }
    out.push_str("}  // namespace polyplug_plugin\n");
    Ok(out)
}

fn generate_cpp_internal_instance_state(
    out: &mut String,
    state_struct: &str,
    class_name: &str,
    symbol: &str,
) {
    out.push_str(&format!(
        "// Per-instance payload carried in GuestContractInstance.data.\n\
         struct {state_struct} {{\n\
         \x20   const HostApi* host;\n\
         \x20   {class_name}* impl;\n\
         }};\n\n\
         // Construction is provided by the generated internal registrar for `{symbol}`.\n\n"
    ));
}

fn resolve_cpp_internal_contract<'a>(
    ir: &'a ValidatedIr,
    contract_impl: &str,
) -> Result<&'a ResolvedContract, PolyplugcError> {
    ir.contracts
        .iter()
        .find(|contract| {
            let identity = format!(
                "{}@{}.{}",
                contract.name, contract.version.major, contract.version.minor
            );
            identity == contract_impl
        })
        .ok_or_else(|| PolyplugcError::ValidationFailed {
            message: format!("C++ internal contract `{contract_impl}` is not resolved"),
        })
}

fn cpp_internal_provider_symbol(plugin_name: &str, contract: &ResolvedContract) -> String {
    format!(
        "{}_{}",
        plugin_name.to_lowercase().replace(['.', '-'], "_"),
        contract_name_to_lower_snake(&contract.name).to_lowercase()
    )
}

fn generate_cpp_guest_plugin_interface(
    out: &mut String,
    plugin_name: &str,
    contract: &ResolvedContract,
    is_native: bool,
    // Contract-id const identifiers already emitted in this namespace. Several plugins
    // may provide the same contract (a valid multi-provider bundle); the const names
    // the contract, so it is emitted once and every provider's interface references it.
    emitted_consts: &mut HashSet<String>,
) -> Result<(), PolyplugcError> {
    let plugin_upper: String = plugin_name.to_uppercase().replace('.', "_");
    let plugin_lower: String = plugin_name.to_lowercase().replace('.', "_");
    // Contract-named id const, unified with the host types file and non-bundle guest
    // (one value, one name everywhere). The interface/fns/instance symbols below stay
    // plugin-named. Several plugins may provide the same contract, so the const is
    // emitted once (first provider) and shared; each provider's interface references it.
    let contract_upper: String = contract_name_to_upper_snake(&contract.name);
    let class_name: String = contract_name_to_guest_contract_class(&contract.name);
    let fn_count: usize = contract.functions.len();

    let state_struct: String = format!("{}InstanceState", snake_to_pascal(&plugin_lower));

    out.push_str(&format!("// Plugin: {}\n", plugin_name));
    if emitted_consts.insert(contract_upper.clone()) {
        out.push_str(&format!(
            "constexpr uint64_t {}_CONTRACT_ID = 0x{:016X}ULL;\n\n",
            contract_upper, contract.contract_id
        ));
    }

    emit_cpp_guest_instance_machinery(
        out,
        &plugin_upper,
        &plugin_lower,
        &class_name,
        &state_struct,
        &contract_upper,
    )?;

    for func in &contract.functions {
        generate_cpp_guest_abi_wrapper(out, &plugin_lower, &state_struct, func)?;
    }

    out.push_str(&format!("static void* const {}_FNS[] = {{\n", plugin_upper));
    for func in &contract.functions {
        out.push_str(&format!(
            "    reinterpret_cast<void*>({0}_{1}_abi),\n",
            plugin_lower, func.name
        ));
    }
    out.push_str("};\n\n");

    out.push_str(&format!(
        "static GuestContractInterface {}_INTERFACE = {{\n",
        plugin_upper
    ));
    out.push_str(&format!("    {}_CONTRACT_ID,\n", contract_upper));
    out.push_str(&format!(
        "    Version{{ {}U, {}U, {}U }},  // contract_version\n",
        contract.version.major, contract.version.minor, contract.version.patch
    ));
    let dispatch_type_str: &str = if is_native {
        "DispatchType::Native"
    } else {
        "DispatchType::VirtualMachine"
    };
    out.push_str(&format!("    {},\n", dispatch_type_str));
    out.push_str("    nullptr,  // adapter_context\n");
    out.push_str(&format!("    {}_create_instance,\n", plugin_upper));
    out.push_str(&format!("    {}_destroy_instance,\n", plugin_upper));
    out.push_str(&format!(
        "    DispatchMechanisms{{ .native = NativeDispatch{{ {fn_count}U, {}_FNS }} }}\n",
        plugin_upper
    ));
    out.push_str("};\n\n");

    Ok(())
}

fn generate_cpp_guest_contract_interface(
    out: &mut String,
    contract: &ResolvedContract,
    is_native: bool,
) -> Result<(), PolyplugcError> {
    let lower: String = contract_name_to_lower_snake(&contract.name);
    let upper: String = contract_name_to_upper_snake(&contract.name);
    let class_name: String = contract_name_to_guest_contract_class(&contract.name);
    let fn_count: usize = contract.functions.len();

    let state_struct: String = format!("{}InstanceState", snake_to_pascal(&lower));

    // Contract ID constant
    out.push_str(&format!(
        "constexpr uint64_t {}_CONTRACT_ID = 0x{:016X}ULL;\n\n",
        upper, contract.contract_id
    ));

    emit_cpp_guest_instance_machinery(out, &upper, &lower, &class_name, &state_struct, &upper)?;

    // ABI wrapper functions — one per function
    for func in &contract.functions {
        generate_cpp_guest_abi_wrapper(out, &lower, &state_struct, func)?;
    }

    // Function pointer array
    out.push_str(&format!("static void* const {}_FNS[] = {{\n", upper));
    for func in &contract.functions {
        out.push_str(&format!(
            "    reinterpret_cast<void*>({0}_{1}_abi),\n",
            lower, func.name
        ));
    }
    out.push_str("};\n\n");

    // Interface static
    out.push_str(&format!(
        "static GuestContractInterface {}_INTERFACE = {{\n",
        upper
    ));
    out.push_str(&format!("    {}_CONTRACT_ID,\n", upper));
    out.push_str(&format!(
        "    Version{{ {}U, {}U, {}U }},  // contract_version\n",
        contract.version.major, contract.version.minor, contract.version.patch
    ));
    let dispatch_type_str: &str = if is_native {
        "DispatchType::Native"
    } else {
        "DispatchType::VirtualMachine"
    };
    out.push_str(&format!("    {},\n", dispatch_type_str));
    out.push_str("    nullptr,  // adapter_context\n");
    out.push_str(&format!("    {}_create_instance,\n", upper));
    out.push_str(&format!("    {}_destroy_instance,\n", upper));
    out.push_str(&format!(
        "    DispatchMechanisms{{ .native = NativeDispatch{{ {}U, {}_FNS }} }}\n",
        fn_count, upper
    ));
    out.push_str("};\n\n");

    Ok(())
}

/// Emit the per-plugin instance machinery: the author-factory forward
/// declaration, the instance payload struct, and the real
/// `create_instance` / `destroy_instance` functions.
///
/// The implementation is constructed by the author factory on every
/// `create_instance` call and carried — together with the HostApi pointer —
/// in `GuestContractInstance.data`. No DSO-global storage is involved, so two
/// runtimes loading the same plugin DSO get fully isolated instances.
/// Render a `interfaces.hpp` free-function definition via langprint. langprint
/// owns the signature (FORM); the caller owns every body byte (LOGIC) through
/// `verbatim_body` — C++ has no post-hoc formatter, so exact whitespace (and
/// even the pre-existing irregular indentation of some wrapper bodies) is baked
/// into `body` and emitted unchanged.
fn render_cpp_defn_fn(
    name: String,
    parameters: Vec<CppParameter>,
    is_static: bool,
    is_inline: bool,
    docs: Vec<String>,
    body: String,
) -> Result<String, PolyplugcError> {
    let func: CppFunction = CppFunction {
        name,
        parent_name: None,
        visibility: CppVisibility::Default,
        parameters,
        template_params: Vec::new(),
        return_type: Some("void".to_owned()),
        is_static,
        is_const: false,
        is_virtual: false,
        is_pure_virtual: false,
        is_inline,
        is_noexcept: true,
        is_override: false,
        is_final: false,
        is_extern_c: false,
        is_friend: false,
        is_deleted: false,
        is_default: false,
        body: Some(vec![body]),
        docs: if docs.is_empty() { None } else { Some(docs) },
    };
    let options: CppFunctionRenderOptions = CppFunctionRenderOptions {
        render_definition: true,
        docs_on_definition: true,
        verbatim_body: true,
        ..CppFunctionRenderOptions::default()
    };
    let backend: CppBackend = CppBackend::default();
    let mut indent_level: i32 = 0;
    backend
        .render_function(
            &func,
            None::<&str>,
            None::<&str>,
            Some(&options),
            &mut indent_level,
        )
        .map_err(|source: io::Error| PolyplugcError::WriteFailed {
            path: "guest/interfaces.hpp".to_owned(),
            source,
        })
}

