/// Generate one guest-side host contract caller class.
fn generate_python_guest_host_contract_caller(
    out: &mut String,
    contract: &ResolvedHostContract,
    enums: &[EnumDef],
) -> Result<(), PolyplugcError> {
    let class_name: String = host_contract_name_to_python_caller(&contract.name);

    out.push_str(&format!(
        "# Guest caller for host contract `{}` (id=0x{:016X})\n",
        contract.name, contract.contract_id
    ));
    out.push_str(&format!("class {}:\n", class_name));
    write_python_docstring(out, "    ", contract.docs.as_deref());

    // langprint renders each method's `def` FORM (indent 1); the bodies are verbatim.
    out.push_str(&render_py_method(
        "__init__",
        py_params(&[
            ("self", ""),
            ("interface", "int"),
            ("instance", "HostContractInstance"),
        ]),
        Some("None".to_owned()),
        None,
        "        self._interface: int = interface\n        self._instance: HostContractInstance = instance".to_owned(),
    )?);
    out.push('\n');

    // Mirrors the canonical rust.rs caller flow: resolve_host_contract_interface
    // yields the interface (dispatch metadata), get_host_contract yields the
    // per-instance state whose .data is the native dispatch's first argument.
    let mut from_host_body: String = String::new();
    from_host_body.push_str("        if host_ptr == 0:\n");
    from_host_body.push_str("            return None\n");
    from_host_body.push_str("        host: Any = ctypes.cast(host_ptr, ctypes.POINTER(HostApi))\n");
    from_host_body.push_str(
        "        # Resolve the contract vtable — the source of dispatch metadata, NOT the instance.\n",
    );
    from_host_body.push_str(&format!(
        "        interface: int | None = host.contents.resolve_host_contract_interface(host_ptr, 0x{:016X}, min_version)\n",
        contract.contract_id
    ));
    from_host_body.push_str("        if not interface:\n");
    from_host_body.push_str("            return None\n");
    from_host_body.push_str(
        "        # Per-instance state; native dispatch functions receive instance.data first.\n",
    );
    from_host_body.push_str(&format!(
        "        instance: HostContractInstance = host.contents.get_host_contract(host_ptr, 0x{:016X}, min_version)\n",
        contract.contract_id
    ));
    from_host_body.push_str("        return cls(interface, instance)");
    out.push_str(&render_py_method(
        "from_host",
        vec![
            PythonParameter {
                name: "cls".to_owned(),
                type_hint: None,
                default: None,
            },
            PythonParameter {
                name: "host_ptr".to_owned(),
                type_hint: Some("int".to_owned()),
                default: None,
            },
            PythonParameter {
                name: "min_version".to_owned(),
                type_hint: Some("int".to_owned()),
                default: Some("0".to_owned()),
            },
        ],
        Some("Self | None".to_owned()),
        Some("    @classmethod\n"),
        from_host_body,
    )?);
    out.push('\n');

    out.push_str(&render_py_method(
        "is_valid",
        py_params(&[("self", "")]),
        Some("bool".to_owned()),
        None,
        "        return self._interface != 0".to_owned(),
    )?);
    out.push('\n');

    for func in &contract.functions {
        generate_python_guest_host_contract_method(out, func, enums)?;
    }

    out.push('\n');
    Ok(())
}

/// Generate one method for a guest-side host contract caller.
fn generate_python_guest_host_contract_method(
    dst: &mut String,
    func: &ResolvedFunction,
    enums: &[EnumDef],
) -> Result<(), PolyplugcError> {
    let fn_id: u32 = func.function_id;
    let return_type: String = match &func.returns {
        Some(ty) => python_guest_caller_return_type_name(ty),
        None => "None".to_owned(),
    };
    let has_return: bool = func.returns.is_some();

    // langprint renders the `def name(self, …) -> ret:` FORM; the body is verbatim.
    let mut parameters: Vec<PythonParameter> = vec![PythonParameter {
        name: "self".to_owned(),
        type_hint: None,
        default: None,
    }];
    for p in &func.params {
        parameters.push(PythonParameter {
            name: p.name.clone(),
            type_hint: Some(python_guest_caller_param_type_name(&p.ty)),
            default: None,
        });
    }

    // The body is accumulated into `body` (aliased as `out` so the existing
    // push_str lines below are unchanged), then rendered as the verbatim slot.
    let mut body: String = String::new();
    let out: &mut String = &mut body;
    if let Some(docs) = python_function_docs(func) {
        out.push_str("        ");
        out.push_str(&python_docstring_literal(&docs));
        out.push('\n');
    }

    out.push_str("        if self._interface == 0:\n");
    if has_return {
        out.push_str("            return None\n");
    } else {
        out.push_str("            return\n");
    }
    out.push_str("        iface: Any = ctypes.cast(self._interface, ctypes.POINTER(HostContractInterface)).contents\n");
    out.push_str("        dispatch_type: int = iface.dispatch_type\n");

    emit_python_guest_host_contract_args_setup(out, func, enums);
    emit_python_guest_host_contract_out_setup(out, &func.returns, enums);

    // Out-param ABI: dispatch writes the AbiError through a trailing pointer.
    out.push_str("        err: AbiError = AbiError()\n");
    out.push_str("        if dispatch_type == DispatchType.Native:\n");
    // Function-id bounds check inside the Native arm only: on a VM interface
    // dispatch.native.function_count aliases bits of dispatch.vm.call through
    // the union (garbage).
    out.push_str(&format!(
        "            if {fn_id} >= iface.dispatch.native.function_count:\n"
    ));
    if has_return {
        out.push_str("                return None\n");
    } else {
        out.push_str("                return\n");
    }
    out.push_str(&format!(
        "            fn_ptr: int = ctypes.cast(iface.dispatch.native.functions + {fn_id} * 8, ctypes.POINTER(ctypes.c_void_p)).contents.value\n"
    ));
    out.push_str(
        "            dispatch_fn: _DISPATCH_FN_CTYPE = ctypes.cast(fn_ptr, _DISPATCH_FN_CTYPE)\n",
    );
    // The native thunk receives the per-instance state (instance.data) as its
    // first argument — mirrors rust.rs `dispatch_fn(self.instance.data, ...)`.
    out.push_str(
        "            dispatch_fn(self._instance.data, args_ptr, out_ptr, ctypes.byref(err))\n",
    );
    out.push_str("        elif dispatch_type == DispatchType.VirtualMachine:\n");
    // The shared VM dispatch ABI receives `user_data` as the host contract's
    // adapter context. Host contracts carry no guest instance, so pass a null
    // GuestContractInstance and no arena.
    out.push_str(&format!(
        "            iface.dispatch.vm.call(iface.user_data, iface.dispatch.vm.loader_data, GuestContractInstance(), {fn_id}, args_ptr, out_ptr, None, ctypes.byref(err))\n"
    ));
    out.push_str("        else:\n");
    if has_return {
        out.push_str("            return None\n");
    } else {
        out.push_str("            return\n");
    }
    out.push_str("        if err.code != AbiErrorCode.Ok:\n");
    if has_return {
        out.push_str("            return None\n");
    } else {
        out.push_str("            return\n");
    }
    emit_python_guest_host_contract_success_return(out, &func.returns, enums);
    if body.ends_with('\n') {
        body.pop();
    }
    dst.push_str(&render_py_method(
        &func.name,
        parameters,
        Some(return_type),
        None,
        body,
    )?);
    dst.push('\n');
    Ok(())
}

/// Emit the args_ptr setup for a Python guest host contract method.
fn emit_python_guest_host_contract_args_setup(
    out: &mut String,
    func: &ResolvedFunction,
    enums: &[EnumDef],
) {
    if func.params.is_empty() {
        out.push_str("        args_ptr: ctypes.c_void_p = ctypes.c_void_p()\n");
        return;
    }

    if func.params.len() == 1 {
        let param: &ResolvedParam = &func.params[0];
        match &param.ty {
            ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => {
                out.push_str(&format!(
                    "        {name}_bytes: bytes = {name}.encode('utf-8')\n",
                    name = param.name
                ));
                out.push_str(&format!(
                    "        {name}_view: StringView = StringView(ptr=ctypes.cast(ctypes.c_char_p({name}_bytes), ctypes.c_void_p), len=len({name}_bytes))\n",
                    name = param.name
                ));
                out.push_str(&format!(
                    "        args_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref({name}_view), ctypes.c_void_p)\n",
                    name = param.name
                ));
            }
            ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => {
                out.push_str(&format!(
                    "        {name}_buf: Buffer = Buffer(ptr=ctypes.c_void_p(ctypes.addressof({name}) if len({name}) > 0 else 0), len=len({name}))\n",
                    name = param.name
                ));
                out.push_str(&format!(
                    "        args_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref({name}_buf), ctypes.c_void_p)\n",
                    name = param.name
                ));
            }
            ResolvedTypeRef::UserDefined(_) => {
                // Enums are IntEnum values: ctypes.byref(IntEnum) is a
                // TypeError, so box the raw repr integer instead.
                if let Some(e) = python_enum_for_type(&param.ty, enums) {
                    let raw_ctype: &str = python_ctype_for_repr(&e.repr);
                    out.push_str(&format!(
                        "        {name}_val: {raw_ctype} = {raw_ctype}(int({name}))\n",
                        name = param.name
                    ));
                    out.push_str(&format!(
                        "        args_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref({name}_val), ctypes.c_void_p)\n",
                        name = param.name
                    ));
                } else {
                    out.push_str(&format!(
                        "        args_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref({}), ctypes.c_void_p)\n",
                        param.name
                    ));
                }
            }
            ResolvedTypeRef::Primitive(_) | ResolvedTypeRef::AbiType(_) => {
                let ty_name: String = python_type_name(&param.ty);
                out.push_str(&format!(
                    "        {name}_val: {ty} = {ty}({name})\n",
                    name = param.name,
                    ty = ty_name
                ));
                out.push_str(&format!(
                    "        args_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref({name}_val), ctypes.c_void_p)\n",
                    name = param.name
                ));
            }
        }
        return;
    }

    // Multiple params: pack into a ctypes.Structure laid out in ABI field order.
    // A plain dict has no stable C layout and `ctypes.addressof(dict)` raises
    // TypeError, so we define a Structure subclass and take the address of an
    // instance of it.
    out.push_str("        class _ArgsPack(ctypes.Structure):\n");
    out.push_str("            _fields_ = [\n");
    for param in &func.params {
        // Enum fields use their repr ctype: ctypes.Structure._fields_ rejects
        // IntEnum classes with a TypeError at class-creation time.
        let param_ty: String = python_pack_field_type(&param.ty, enums);
        out.push_str(&format!(
            "                (\"{}\", {}),\n",
            param.name, param_ty
        ));
    }
    out.push_str("            ]\n");
    out.push_str("        args_val: _ArgsPack = _ArgsPack()\n");
    for param in &func.params {
        match &param.ty {
            ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => {
                out.push_str(&format!(
                    "        {name}_bytes: bytes = {name}.encode('utf-8')\n",
                    name = param.name
                ));
                out.push_str(&format!(
                    "        args_val.{name} = StringView(ptr=ctypes.cast(ctypes.c_char_p({name}_bytes), ctypes.c_void_p), len=len({name}_bytes))\n",
                    name = param.name
                ));
            }
            ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => {
                out.push_str(&format!(
                    "        args_val.{name} = Buffer(ptr=ctypes.c_void_p(ctypes.addressof({name}) if len({name}) > 0 else 0), len=len({name}))\n",
                    name = param.name
                ));
            }
            _ => {
                if python_enum_for_type(&param.ty, enums).is_some() {
                    // IntEnum is an int subclass; store the raw repr integer.
                    out.push_str(&format!("        args_val.{0} = int({0})\n", param.name));
                } else {
                    out.push_str(&format!("        args_val.{0} = {0}\n", param.name));
                }
            }
        }
    }
    out.push_str(
        "        args_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref(args_val), ctypes.c_void_p)\n",
    );
}

/// Emit the out_ptr setup for a Python guest host contract method.
fn emit_python_guest_host_contract_out_setup(
    out: &mut String,
    returns: &Option<ResolvedTypeRef>,
    enums: &[EnumDef],
) {
    if let Some(ret_ty) = returns {
        let py_ty: String = python_guest_caller_return_type_name(ret_ty);
        // Enum returns: the out slot is the enum's repr ctype. An IntEnum class
        // is not a ctypes type — `EnumName()` has no zero-arg constructor and
        // ctypes.byref(IntEnum) is a TypeError. The success return converts the
        // raw repr integer back with `EnumName(result.value)`.
        if let Some(e) = python_enum_for_type(ret_ty, enums) {
            let raw_ctype: &str = python_ctype_for_repr(&e.repr);
            out.push_str(&format!("        result: {raw_ctype} = {raw_ctype}()\n"));
            out.push_str("        out_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref(result), ctypes.c_void_p)\n");
        } else if matches!(ret_ty, ResolvedTypeRef::AbiType(AbiBuiltin::StringView)) {
            out.push_str("        result: StringView = StringView()\n");
            out.push_str("        out_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref(result), ctypes.c_void_p)\n");
        } else if matches!(ret_ty, ResolvedTypeRef::AbiType(AbiBuiltin::Buffer)) {
            out.push_str("        result: Buffer = Buffer()\n");
            out.push_str("        out_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref(result), ctypes.c_void_p)\n");
        } else if matches!(ret_ty, ResolvedTypeRef::UserDefined(_)) {
            out.push_str(&format!("        result: {py_ty} = {py_ty}()\n"));
            out.push_str("        out_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref(result), ctypes.c_void_p)\n");
        } else {
            let ctypes_ty: String = python_type_name(ret_ty);
            out.push_str(&format!("        result: {ctypes_ty} = {ctypes_ty}()\n"));
            out.push_str("        out_ptr: ctypes.c_void_p = ctypes.cast(ctypes.byref(result), ctypes.c_void_p)\n");
        }
    } else {
        out.push_str("        out_ptr: ctypes.c_void_p = ctypes.c_void_p()\n");
    }
}

/// Generate `guest/host_contracts.py` — caller classes for guest-side host contract callers.
fn generate_guest_host_contracts_file(ir: &ValidatedIr) -> Result<String, PolyplugcError> {
    let mut out: String = String::new();
    out.push_str(PY_HEADER);
    let mut stdlib: Vec<ImportEntry> = vec![py_import("ctypes")];
    stdlib.extend(py_from("typing", &["Any", "Self"]));
    out.push_str(&python_import_block(&[
        &py_from("__future__", &["annotations"]),
        &stdlib,
        &py_from(
            "polyplug_abi",
            &[
                "AbiErrorCode",
                "AbiError",
                "Buffer",
                "DispatchType",
                "GuestContractInstance",
                "HostContractInstance",
                "HostContractInterface",
                "HostApi",
                "StringView",
            ],
        ),
    ]));
    out.push('\n');

    let type_imports: BTreeSet<String> = collect_python_guest_host_contract_type_imports(ir);
    if !type_imports.is_empty() {
        let import_list: String = type_imports.into_iter().collect::<Vec<String>>().join(", ");
        let symbols: Vec<&str> = import_list.split(", ").collect();
        out.push_str(&python_import_block(&[&py_from("guest.types", &symbols)]));
        out.push('\n');
    }

    // Out-param native dispatch: fn(instance, args, out, out_err) -> void.
    out.push_str(
        "_DISPATCH_FN_CTYPE = ctypes.CFUNCTYPE(None, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p)\n\n",
    );

    for contract in &ir.host_contracts {
        generate_python_guest_host_contract_caller(&mut out, contract, &ir.enums)?;
    }

    // Emit contract ID constants
    out.push_str("# Contract ID constants\n");
    for contract in &ir.host_contracts {
        let class_name: String = host_contract_name_to_python_caller(&contract.name);
        let const_name: String = format!("{}_ID", class_name.to_uppercase());
        out.push_str(&format!(
            "{}: int = 0x{:016X}\n",
            const_name, contract.contract_id
        ));
    }

    Ok(out)
}

/// Collect type imports needed for guest host contract callers.
fn collect_python_guest_host_contract_type_imports(ir: &ValidatedIr) -> BTreeSet<String> {
    let mut imports: BTreeSet<String> = BTreeSet::new();
    for contract in &ir.host_contracts {
        for func in &contract.functions {
            for param in &func.params {
                if let ResolvedTypeRef::UserDefined(name) = &param.ty {
                    imports.insert(name.clone());
                }
            }
            if let Some(ResolvedTypeRef::UserDefined(name)) = &func.returns {
                imports.insert(name.clone());
            }
        }
    }
    imports
}

/// Generate `guest/host_contracts.pyi` — type stubs for guest host contract callers.
fn generate_guest_host_contracts_stub(ir: &ValidatedIr) -> String {
    let mut out: String = String::new();
    out.push_str(PY_HEADER);
    out.push_str(&python_import_block(&[
        &py_from("__future__", &["annotations"]),
        &py_from("typing", &["Any", "Self"]),
        &py_from("polyplug_abi", &["HostContractInstance"]),
    ]));
    out.push('\n');

    let type_imports: BTreeSet<String> = collect_python_guest_host_contract_type_imports(ir);
    if !type_imports.is_empty() {
        let import_list: String = type_imports.into_iter().collect::<Vec<String>>().join(", ");
        let symbols: Vec<&str> = import_list.split(", ").collect();
        out.push_str(&python_import_block(&[&py_from("guest.types", &symbols)]));
        out.push('\n');
    }

    for contract in &ir.host_contracts {
        let class_name: String = host_contract_name_to_python_caller(&contract.name);
        out.push_str(&format!("class {}:\n", class_name));
        write_python_docstring(&mut out, "    ", contract.docs.as_deref());
        out.push_str(
            "    def __init__(self, interface: int, instance: HostContractInstance) -> None: ...\n",
        );
        out.push_str("    @classmethod\n");
        out.push_str(
            "    def from_host(cls, host_ptr: int, min_version: int = 0) -> Self | None: ...\n",
        );
        out.push_str("    def is_valid(self) -> bool: ...\n");
        for func in &contract.functions {
            let return_type: String = match &func.returns {
                Some(ty) => python_guest_caller_return_type_name(ty),
                None => "None".to_owned(),
            };
            let params_str: String = if func.params.is_empty() {
                String::new()
            } else {
                func.params
                    .iter()
                    .map(|p: &ResolvedParam| {
                        let py_ty: String = python_guest_caller_param_type_name(&p.ty);
                        format!(", {}: {}", p.name, py_ty)
                    })
                    .collect::<Vec<_>>()
                    .join("")
            };
            if let Some(docs) = python_function_docs(func) {
                out.push_str(&format!(
                    "    def {}(self{}) -> {}:\n",
                    func.name, params_str, return_type
                ));
                write_python_docstring(&mut out, "        ", Some(&docs));
                out.push_str("        ...\n");
            } else {
                out.push_str(&format!(
                    "    def {}(self{}) -> {}: ...\n",
                    func.name, params_str, return_type
                ));
            }
        }
        out.push('\n');
    }

    // Contract ID constants in stub
    for contract in &ir.host_contracts {
        let class_name: String = host_contract_name_to_python_caller(&contract.name);
        let const_name: String = format!("{}_ID", class_name.to_uppercase());
        out.push_str(&format!("{}: int\n", const_name));
    }

    out
}

fn generate_bundle_manifest_python(ir: &ValidatedIr) -> String {
    let bundle: &ResolvedBundle = match ir.bundle.as_ref() {
        Some(b) => b,
        None => return String::from("# ERROR: bundle manifest called without bundle IR\n"),
    };

    let name: &str = &bundle.name;
    let version: String = format!(
        "{}.{}.{}",
        bundle.version.major, bundle.version.minor, bundle.version.patch
    );
    let file_field: String = super::format_manifest_file_field(&bundle.file);

    // Collect provides: all implements from all plugins, deduplicated
    let mut provides: Vec<String> = bundle
        .plugins
        .iter()
        .flat_map(|p: &ResolvedPlugin| p.implements.iter().cloned())
        .map(|impl_str: String| {
            if let Some(at_pos) = impl_str.find('@') {
                let contract_name: &str = &impl_str[..at_pos];
                let version_part: &str = &impl_str[at_pos + 1..];
                if let Some(dot_pos) = version_part.find('.') {
                    let major: &str = &version_part[..dot_pos];
                    format!("{}@{}", contract_name, major)
                } else {
                    impl_str
                }
            } else {
                impl_str
            }
        })
        .collect();
    provides.sort();
    provides.dedup();

    let provides_toml: String = if provides.is_empty() {
        String::from("[]")
    } else {
        format!(
            "[{}]",
            provides
                .iter()
                .map(|s: &String| format!("\"{}\"", s))
                .collect::<Vec<_>>()
                .join(", ")
        )
    };

    let provides_set: HashSet<String> = provides.iter().cloned().collect();
    let fn_count_entries: Vec<String> = ir
        .contracts
        .iter()
        .filter(|c: &&ResolvedContract| {
            provides_set.contains(&format!("{}@{}", c.name, c.version.major))
        })
        .map(|c: &ResolvedContract| {
            let fn_count: u32 = c.functions.len() as u32;
            format!("\"{}@{}\" = {}", c.name, c.version.major, fn_count)
        })
        .collect();
    let function_count_toml: String = format!("{{ {} }}", fn_count_entries.join(", "));

    let reinit: bool = bundle.needs_reinit_on_dep_reload;

    let dep_toml: String = super::emit_manifest_dependencies(&bundle.dependencies);

    let loader: &str = &bundle.loader;

    format!(
        "# THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n\
         name = \"{name}\"\n\
         id = {bundle_id}\n\
         version = \"{version}\"\n\
         loader = \"{loader}\"\n\
         provides = {provides_toml}\n\
         function_count = {function_count_toml}\n\
         needs_reinit_on_dep_reload = {reinit}\n\
         {file_field}\n\
         {dep_toml}",
        bundle_id = bundle.bundle_id
    )
}

fn to_upper_snake_case(s: &str) -> String {
    let mut result: String = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            result.push('_');
        }
        result.extend(c.to_uppercase());
    }
    result
}

fn substitute_variant_refs_python(declared_variants: &[EnumVariant], expr: &str) -> String {
    let chars: Vec<char> = expr.chars().collect();
    let len: usize = chars.len();
    let mut result: String = String::new();
    let mut i: usize = 0;
    while i < len {
        let c: char = chars[i];
        if c.is_alphabetic() || c == '_' {
            let start: usize = i;
            while i < len && (chars[i].is_alphanumeric() || chars[i] == '_') {
                i += 1;
            }
            let ident: String = chars[start..i].iter().collect();
            let found_variant: Option<&EnumVariant> =
                declared_variants.iter().find(|v| v.name == ident);
            if let Some(ref_variant) = found_variant {
                result.push('(');
                result.push_str(&ref_variant.value);
                result.push(')');
            } else {
                result.push_str(&ident);
            }
        } else {
            result.push(c);
            i += 1;
        }
    }
    result
}

fn generate_python_enum(out: &mut String, e: &EnumDef) -> Result<(), PolyplugcError> {
    let base_class: &str = if e.bitflag {
        "enum.IntFlag"
    } else {
        "enum.IntEnum"
    };
    let py_enum: PythonEnum = PythonEnum {
        name: e.name.clone(),
        base_class: base_class.to_owned(),
        members: e
            .variants
            .iter()
            .map(|variant| PythonEnumMember {
                name: to_upper_snake_case(&variant.name),
                value: substitute_variant_refs_python(&e.variants, &variant.value),
            })
            .collect(),
        docstring: None,
    };
    let mut indent_level: i32 = 0;
    let mut rendered: String = PythonBackend::default()
        .render_enum(
            &py_enum,
            None::<&str>,
            None::<&str>,
            None,
            &mut indent_level,
        )
        .map_err(|source: io::Error| PolyplugcError::WriteFailed {
            path: "types.py".to_owned(),
            source,
        })?;
    let mut docs: Vec<String> = doc_lines(e.docs.as_deref())
        .into_iter()
        .map(str::to_owned)
        .collect();
    for variant in &e.variants {
        if let Some(variant_docs) = variant.docs.as_deref() {
            if !docs.is_empty() {
                docs.push(String::new());
            }
            docs.push(format!(
                "{}: {}",
                variant.name,
                variant_docs.replace('\n', "\n    ")
            ));
        }
    }
    if !docs.is_empty() {
        let class_end: usize = rendered.find('\n').unwrap_or(rendered.len());
        rendered.insert_str(
            class_end + usize::from(class_end < rendered.len()),
            &format!("    {}\n", python_docstring_literal(&docs.join("\n"))),
        );
    }
    out.push_str(&rendered);
    Ok(())
}

