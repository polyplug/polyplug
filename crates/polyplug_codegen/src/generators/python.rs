fn generate_guest_contracts_file(ir: &ValidatedIr) -> Result<String, PolyplugcError> {
    let mut out: String = String::new();
    out.push_str(PY_HEADER);
    // `struct` is only used by the precompiled scalar (un)pack consts; emit the
    // import only when at least one function has scalar args or a scalar return.
    let any_struct_const: bool = ir
        .contracts
        .iter()
        .any(|c: &ResolvedContract| c.functions.iter().any(fn_uses_struct_const));
    let any_string_arg: bool = ir
        .contracts
        .iter()
        .any(|c: &ResolvedContract| c.functions.iter().any(fn_has_stringview_arg));
    // `alloc_string_arena` is used for a StringView return AND for any struct or
    // array return, whose marshaler allocates embedded strings from the arena.
    let any_string_ret: bool = ir.contracts.iter().any(|c: &ResolvedContract| {
        c.functions.iter().any(|f: &ResolvedFunction| {
            fn_returns_stringview(f)
                || matches!(
                    &f.returns,
                    Some(ResolvedTypeRef::UserDefined(name))
                        if !ir.enums.iter().any(|e: &EnumDef| &e.name == name)
                )
        })
    });

    // stdlib group: ctypes always; struct only for scalar (un)pack consts;
    // typing.Callable types the author-factory slots, Any the registrations list.
    let mut stdlib: Vec<ImportEntry> = vec![py_import("ctypes")];
    if any_struct_const {
        stdlib.push(py_import("struct"));
    }
    stdlib.extend(py_from("typing", &["Any", "Callable"]));

    // project group: polyplug_abi StringView/to_str only when a function takes a
    // StringView; polyplug_guest always (register_contract + AbiError/AbiErrorCode
    // for the (registrations, AbiError) return), plus alloc_string_arena on a
    // StringView/struct/array return; guest.types for any user-defined types.
    let mut project: Vec<ImportEntry> = Vec::new();
    // `StringView` is referenced directly when a function takes a StringView arg
    // (read via `to_str`) OR returns an `Array<StringView>` (the element marshaler
    // overlays `StringView` on arena memory). `to_str` is only for reading args.
    let any_stringview_array_ret: bool = ir.contracts.iter().any(|c: &ResolvedContract| {
        c.functions
            .iter()
            .any(|f: &ResolvedFunction| return_has_stringview_array(&f.returns, ir))
    });
    if any_string_arg {
        project.extend(py_from("polyplug_abi", &["StringView", "to_str"]));
    } else if any_stringview_array_ret {
        project.extend(py_from("polyplug_abi", &["StringView"]));
    }
    let guest_syms: &[&str] = if any_string_ret {
        &[
            "register_contract",
            "alloc_string_arena",
            "AbiError",
            "AbiErrorCode",
        ]
    } else {
        &["register_contract", "AbiError", "AbiErrorCode"]
    };
    project.extend(py_from("polyplug_guest", guest_syms));
    let type_imports: BTreeSet<String> = collect_python_type_imports(ir);
    for ty in &type_imports {
        project.push(ImportEntry::PyFrom {
            module: "guest.types".to_string(),
            symbol: ty.clone(),
        });
    }

    out.push_str(&python_import_block(&[
        &py_from("__future__", &["annotations"]),
        &stdlib,
        &project,
    ]));
    out.push('\n');

    out.push_str("POLYPLUG_ABI_VERSION: int = 1\n\n");

    // VM dispatch: Python plugins are VM-dispatch plugins. polyplug_init builds a
    // local registrations list via `register_contract` and RETURNS it together with
    // an AbiError as a `(registrations, AbiError)` tuple. The polyplug_python loader
    // reads that return value — nothing is deposited into the module namespace. The
    // loader wraps each function in a VM-dispatch trampoline and registers the
    // contract itself, then routes every per-call invocation through the `vm.call`
    // transport. The guest therefore never builds a GuestContractInterface, never
    // registers native function pointers, and never returns an AbiError from a
    // ctypes callback — the previous sret-emulating ctypes path was undefined
    // behaviour on arm64 and is gone.
    //
    // Each generated `<plugin>_<fn>_abi(args_ptr, out_ptr, arena_ptr, arena_alloc)`
    // callable receives three raw pointers as Python ints (arena_ptr is 0 when null)
    // and the loader-supplied arena allocator as its final argument. It unmarshals
    // args, invokes the user impl, marshals the return into out_ptr (forwarding
    // arena_alloc for arena-backed string returns), and returns normally on success
    // or raises on failure (the loader maps a raised exception to AbiErrorCode.Generic).

    let mut registrations: Vec<(String, String, String, &ResolvedContract)> = Vec::new();
    if let Some(bundle) = &ir.bundle {
        for plugin in &bundle.plugins {
            for contract_impl in &plugin.implements {
                if let Some(contract) = ir.contracts.iter().find(|c| {
                    let contract_full =
                        format!("{}@{}.{}", c.name, c.version.major, c.version.minor);
                    &contract_full == contract_impl
                }) {
                    generate_guest_plugin_trait(&mut out, &plugin.name, contract)?;
                    generate_guest_plugin_interface(&mut out, &plugin.name, contract, ir)?;
                    let plugin_lower: String = plugin.name.to_lowercase().replace('.', "_");
                    registrations.push((
                        plugin.name.clone(),
                        plugin_lower.clone(),
                        plugin_lower,
                        contract,
                    ));
                }
            }
        }
    } else {
        for contract in &ir.contracts {
            generate_guest_contract_trait(&mut out, contract)?;
            generate_guest_contract_interface(&mut out, contract, ir)?;
            let lower: String = contract.name.replace('.', "_");
            let upper: String = contract_name_to_upper_snake(&contract.name);
            registrations.push((contract.name.clone(), lower, upper, contract));
        }
    }

    // polyplug_abi_version + polyplug_init are module entry points: langprint owns
    // the `def ... -> ...:` FORM, polyplugc bakes the verbatim bodies (docstring +
    // registration logic) below.
    out.push_str(&render_py_defn_fn(
        "polyplug_abi_version".to_owned(),
        Vec::new(),
        Some("int".to_owned()),
        "    return 1".to_owned(),
    )?);
    out.push('\n');

    let mut init_body: String = String::new();
    init_body.push_str(
        "    \"\"\"Build this bundle's contract registrations for the polyplug_python VM loader.\n",
    );
    init_body.push('\n');
    init_body.push_str(
        "    Returns a `(registrations, abi_error)` tuple: the loader reads this return\n",
    );
    init_body.push_str(
        "    value (nothing is deposited into the module namespace) and, when `abi_error.code\n",
    );
    init_body.push_str(
        "    == AbiErrorCode.Ok`, registers each contract in `registrations` itself. A factory\n",
    );
    init_body.push_str(
        "    that was never set at import time yields `([], AbiError(code=AbiErrorCode.Generic))`.\n\n",
    );
    init_body.push_str("    Args:\n");
    init_body
        .push_str("        host_ptr: HostApi pointer — passed to each author factory so every\n");
    init_body.push_str(
        "                  implementation is constructed with its owning runtime's host\n",
    );
    init_body.push_str("                  (no host pointer is stored in the guest SDK).\n");
    init_body.push_str("        ctx_ptr: BundleInitContext pointer (unused)\n\n");
    init_body.push_str("    Returns:\n");
    init_body
        .push_str("        (registrations, abi_error) — the loader consumes registrations only\n");
    init_body.push_str("        when abi_error.code == AbiErrorCode.Ok.\n");
    init_body.push_str("    \"\"\"\n");
    // The loader owns per-instance state: it calls each contract's factory once
    // per create_instance with the runtime's host pointer. polyplug_init only
    // registers the factory and callables, so host_ptr is unused here.
    init_body.push_str("    _ = host_ptr\n");
    init_body.push_str("    _ = ctx_ptr\n");
    init_body.push_str("    registrations: list[dict[str, Any]] = []\n");
    for (_, _, impl_var, _) in &registrations {
        init_body.push_str(&format!("    if _{impl_var}_FACTORY is None:\n"));
        init_body.push_str("        return [], AbiError(code=int(AbiErrorCode.Generic))\n");
    }
    for (display_name, lower, impl_var, contract) in &registrations {
        let contract_str: String = format!("{}@{}", contract.name, contract.version.major);
        init_body.push_str("    register_contract(\n");
        init_body.push_str("        registrations,\n");
        init_body.push_str(&format!("        contract=\"{contract_str}\",\n"));
        init_body.push_str(&format!("        factory=_{impl_var}_FACTORY,\n"));
        init_body.push_str("        functions=[\n");
        for func in &contract.functions {
            init_body.push_str(&format!("            {lower}_{}_abi,\n", func.name));
        }
        init_body.push_str("        ],\n");
        init_body.push_str(&format!("        plugin_name=\"{display_name}\",\n"));
        init_body.push_str("    )\n");
    }
    init_body.push_str("    return registrations, AbiError(code=int(AbiErrorCode.Ok))");
    out.push_str(&render_py_defn_fn(
        "polyplug_init".to_owned(),
        py_params(&[("host_ptr", "int"), ("ctx_ptr", "int")]),
        Some("tuple[list[dict[str, Any]], AbiError]".to_owned()),
        init_body,
    )?);
    out.push('\n');

    Ok(out)
}

/// Whether a function returns a `StringView` (the variable-size return the guest
/// glue allocates from the call arena via the loader-supplied `arena_alloc`).
fn fn_returns_stringview(func: &ResolvedFunction) -> bool {
    matches!(
        func.returns,
        Some(ResolvedTypeRef::AbiType(AbiBuiltin::StringView))
    )
}

/// Whether a function takes a `StringView` parameter (the guest glue views it
/// and transcodes it to `str` via `to_str`).
fn fn_has_stringview_arg(func: &ResolvedFunction) -> bool {
    func.params
        .iter()
        .any(|p: &ResolvedParam| matches!(p.ty, ResolvedTypeRef::AbiType(AbiBuiltin::StringView)))
}

/// Whether a function emits a precompiled `struct.Struct` const (scalar args via
/// the no-padding fast path, or a scalar return).
fn fn_uses_struct_const(func: &ResolvedFunction) -> bool {
    let scalar_args: bool = uses_scalar_args_struct(&func.params);
    let scalar_ret: bool = func
        .returns
        .as_ref()
        .is_some_and(|ty: &ResolvedTypeRef| scalar_struct_format_char(ty).is_some());
    scalar_args || scalar_ret
}

