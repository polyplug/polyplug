fn python_function_docs(func: &ResolvedFunction) -> Option<String> {
    let mut lines: Vec<String> = doc_lines(func.docs.as_deref())
        .into_iter()
        .map(str::to_owned)
        .collect();
    let documented_params: Vec<&ResolvedParam> = func
        .params
        .iter()
        .filter(|param| param.docs.is_some())
        .collect();
    if !documented_params.is_empty() {
        if !lines.is_empty() {
            lines.push(String::new());
        }
        lines.push("Args:".to_owned());
        for param in documented_params {
            if let Some(docs) = param.docs.as_deref() {
                lines.push(format!(
                    "    {}: {}",
                    param.name,
                    docs.replace('\n', "\n        ")
                ));
            }
        }
    }
    if let Some(return_docs) = func.return_docs.as_deref() {
        if !lines.is_empty() {
            lines.push(String::new());
        }
        lines.push("Returns:".to_owned());
        lines.push(format!("    {}", return_docs.replace('\n', "\n    ")));
    }
    (!lines.is_empty()).then(|| lines.join("\n"))
}

fn generate_python_user_type(out: &mut String, ty: &ResolvedType, enums: &[EnumDef]) {
    out.push_str(&format!("class {}(ctypes.Structure):\n", ty.name));
    write_python_docstring(out, "    ", ty.docs.as_deref());
    out.push_str("    _fields_: ClassVar = [\n");
    for field in &ty.fields {
        // An enum field uses its repr ctype: `ctypes.Structure._fields_` rejects an
        // `enum.IntEnum` class ("this type has no size") at class-creation time.
        let field_ty: String = match python_enum_for_type(&field.ty, enums) {
            Some(e) => python_ctype_for_repr(&e.repr).to_owned(),
            None => python_type_name(&field.ty),
        };
        for line in doc_lines(field.docs.as_deref()) {
            out.push_str(&format!("        #: {line}\n"));
        }
        out.push_str(&format!("        (\"{}\", {}),\n", field.name, field_ty));
    }
    out.push_str("    ]\n");
}

