fn generate_guest_contracts_file(ir: &ValidatedIr) -> String {
    let mut out: String = String::new();
    out.push_str(PY_HEADER);
    out.push_str("from __future__ import annotations\n");
    out.push_str("import ctypes\n");
    out.push_str("from typing import Any, Callable, TYPE_CHECKING, TypeAlias\n");
    out.push_str("from polyplug_guest.abi import ABI_ERROR_GENERIC, ABI_ERROR_INVALID_POINTER, ABI_OK, AbiError, DispatchType, HostVTable, PluginContext, PluginDescriptor, PluginInterface, StringView\n");
    out.push_str("from polyplug_guest import store_host_vtable\n\n");
    out.push_str("if TYPE_CHECKING:\n");
    out.push_str("    from ctypes import _Pointer as _CtypesPointer\n");
    out.push_str("    ctypes.POINTER = _CtypesPointer  # type: ignore[assignment]\n\n");

    let type_imports: BTreeSet<String> = collect_python_type_imports(ir);
    if !type_imports.is_empty() {
        let import_list: String = type_imports.into_iter().collect::<Vec<String>>().join(", ");
        out.push_str(&format!("from guest.types import {}\n\n", import_list));
    }

    out.push_str("POLYPLUG_ABI_VERSION: int = 1\n");
    out.push_str("class _AbiError(ctypes.Structure):\n");
    out.push_str("    _fields_ = [\n");
    out.push_str("        ('code', ctypes.c_uint32),\n");
    out.push_str("        ('_pad', ctypes.c_uint32),\n");
    out.push_str("        ('message_ptr', ctypes.c_void_p),\n");
    out.push_str("        ('message_len', ctypes.c_size_t),\n");
    out.push_str("    ]\n\n");
    out.push_str(
        "_DISPATCH_FN_CTYPE = ctypes.CFUNCTYPE(_AbiError, ctypes.c_void_p, ctypes.c_void_p)\n",
    );
    out.push_str(
        "_DISPATCH_FN_TYPE: TypeAlias = Callable[[ctypes.c_void_p, ctypes.c_void_p], _AbiError]\n\n",
    );

    if let Some(bundle) = &ir.bundle {
        for plugin in &bundle.plugins {
            for contract_impl in &plugin.implements {
                if let Some(contract) = ir.contracts.iter().find(|c| {
                    let contract_full =
                        format!("{}@{}.{}", c.name, c.version.major, c.version.minor);
                    &contract_full == contract_impl
                }) {
                    generate_guest_plugin_trait(&mut out, &plugin.name, contract);
                    generate_guest_plugin_vtable(
                        &mut out,
                        &plugin.name,
                        contract,
                        is_native_runtime(&bundle.runtime),
                    );
                }
            }
        }
    } else {
        for contract in &ir.contracts {
            generate_guest_contract_trait(&mut out, contract);
            generate_guest_contract_vtable(&mut out, contract, true);
        }
    }

    out.push_str("def polyplug_abi_version() -> int:\n");
    out.push_str("    return 1\n\n");
    out.push_str("def polyplug_init(rt_ctx: int, host_ptr: int, ctx_ptr: int) -> None:\n");
    out.push_str("    if rt_ctx == 0:\n");
    out.push_str("        return\n");
    out.push_str("    if host_ptr == 0:\n");
    out.push_str("        return\n");
    out.push_str("    if ctx_ptr == 0:\n");
    out.push_str("        return\n");
    out.push_str("    store_host_vtable(host_ptr)\n");
    out.push_str("    ctx: PluginContext = PluginContext.from_address(ctx_ptr)\n");
    out.push_str("    host: Any = ctypes.cast(host_ptr, ctypes.POINTER(HostVTable))\n");

    if let Some(bundle) = &ir.bundle {
        for plugin in &bundle.plugins {
            let plugin_upper: String = plugin.name.to_uppercase().replace('.', "_");
            out.push_str(&format!(
                "    err_{plugin_upper}: AbiError = host.contents.register_plugin(\n"
            ));
            out.push_str(&format!("        rt_ctx, ctypes.byref({plugin_upper}_DESCRIPTOR), ctypes.byref({plugin_upper}_VTABLE)\n"));
            out.push_str("    )\n");
            out.push_str(&format!("    if err_{plugin_upper}.code != ABI_OK:\n"));
            out.push_str("        raise RuntimeError(\"plugin registration failed\")\n\n");
        }
    } else {
        for contract in &ir.contracts {
            let upper: String = contract_name_to_upper_snake(&contract.name);
            out.push_str(&format!(
                "    err_{upper}: AbiError = host.contents.register_plugin(\n"
            ));
            out.push_str(&format!(
                "        rt_ctx, ctypes.byref({upper}_DESCRIPTOR), ctypes.byref({upper}_VTABLE)\n"
            ));
            out.push_str("    )\n");
            out.push_str(&format!("    if err_{upper}.code != ABI_OK:\n"));
            out.push_str("        raise RuntimeError(\"plugin registration failed\")\n\n");
        }
    }

    out
}

