//! C++ code generator for polyplugc.
//!
//! Generates:
//! - Host-side: header-only C++ callers (RAII wrapper + vtable dispatch)
//! - Guest-side: extern \"C\" ABI wrappers + operator new/delete overrides

use crate::error::CodegenError;
use crate::generators::CodeGenerator;
use crate::generators::GeneratedFile;
use crate::generators::GeneratedFiles;
use crate::ir::AbiBuiltin;
use crate::ir::PrimitiveType;
use crate::ir::ResolvedContract;
use crate::ir::ResolvedType;
use crate::ir::ResolvedTypeRef;
use crate::ir::ValidatedIr;

/// The C++ code generator.
pub(crate) struct CppGenerator;

impl CodeGenerator for CppGenerator {
    fn language_name(&self) -> &'static str {
        "cpp"
    }

    fn generate_host(
        &self,
        ir: &ValidatedIr,
        files: &mut GeneratedFiles,
    ) -> Result<(), CodegenError> {
        let mut out: String = String::new();
        out.push_str("// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n");
        out.push_str(
            "// Re-generate with: polyplugc generate --api api.toml --lang cpp --out <dir>\n\n",
        );
        out.push_str("#pragma once\n");
        out.push_str("#include \"polyplug/abi.hpp\"\n\n");
        out.push_str("static_assert(POLYPLUG_ABI_VERSION == 1,\n");
        out.push_str("    \"polyplug header version mismatch\");\n\n");

        for ty in &ir.types {
            generate_cpp_type(&mut out, ty);
        }

        for contract in &ir.contracts {
            generate_cpp_host_contract(&mut out, contract)?;
        }

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("host_callers.hpp"),
            content: out,
        });
        Ok(())
    }

    fn generate_guest(
        &self,
        ir: &ValidatedIr,
        files: &mut GeneratedFiles,
    ) -> Result<(), CodegenError> {
        let mut out: String = String::new();
        out.push_str("// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n");
        out.push_str("// Re-generate with: polyplugc generate --bundle bundle.toml --lang cpp --out <dir>\n\n");
        out.push_str("#pragma once\n");
        out.push_str("#include \"polyplug_guest.hpp\"\n\n");
        out.push_str("// Guest allocator hookup\n");
        out.push_str("#include <new>\n");
        out.push_str("void* operator new(std::size_t size) { return polyplug_host_alloc(size, alignof(std::max_align_t)); }\n");
        out.push_str("void operator delete(void* ptr, std::size_t size) noexcept { polyplug_host_free(ptr, size, alignof(std::max_align_t)); }\n\n");

        if let Some(ref bundle) = ir.bundle {
            for plugin in &bundle.plugins {
                out.push_str(&format!("// Plugin: {}\n", plugin.name));
                for contract_name in &plugin.implements {
                    out.push_str(&format!(
                        "// TODO: implement vtable for contract: {contract_name}\n"
                    ));
                }
            }
        }

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("guest_sdk.hpp"),
            content: out,
        });
        Ok(())
    }
}

fn generate_cpp_type(out: &mut String, ty: &ResolvedType) {
    out.push_str(&format!("/// User-defined type `{}`\n", ty.name));
    out.push_str("struct ");
    out.push_str(&ty.name);
    out.push_str(" {\n");
    for field in &ty.fields {
        out.push_str(&format!(
            "    {} {};\n",
            cpp_type_name(&field.ty),
            field.name
        ));
    }
    out.push_str("};\n\n");
}

fn generate_cpp_host_contract(
    out: &mut String,
    contract: &ResolvedContract,
) -> Result<(), CodegenError> {
    let class_name: String = contract_name_to_class(&contract.name);
    out.push_str(&format!(
        "/// Host caller for contract `{}` (id=0x{:016X})\n",
        contract.name, contract.contract_id
    ));
    out.push_str(&format!("class {} {{\npublic:\n", class_name));
    out.push_str("    explicit constexpr ");
    out.push_str(&class_name);
    out.push_str("(PluginHandle h) noexcept : handle_(h) {}\n");

    for func in &contract.functions {
        out.push_str(&format!("    // function_id={}\n", func.function_id));
        let return_type: String = func
            .returns
            .as_ref()
            .map(cpp_type_name)
            .unwrap_or_else(|| "void".to_owned());
        out.push_str(&format!("    {} {}(", return_type, func.name));
        let params: Vec<String> = func
            .params
            .iter()
            .map(|p| format!("{} {}", cpp_type_name(&p.ty), p.name))
            .collect();
        out.push_str(&params.join(", "));
        out.push_str(");\n");
    }

    out.push_str("private:\n    PluginHandle handle_;\n};\n\n");
    Ok(())
}

fn cpp_type_name(ty: &ResolvedTypeRef) -> String {
    match ty {
        ResolvedTypeRef::Primitive(p) => p.cpp_name().to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => "StringView".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => "Buffer".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Ptr) => "void*".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Void) => "void".to_owned(),
        ResolvedTypeRef::UserDefined(name) => name.clone(),
    }
}

fn contract_name_to_class(name: &str) -> String {
    // Convert "image.decode" -> "ImageDecodeContract"
    name.split('.')
        .map(|p| {
            let mut chars: core::str::Chars<'_> = p.chars();
            match chars.next() {
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join("")
        + "Contract"
}

// Suppress unused import warning
