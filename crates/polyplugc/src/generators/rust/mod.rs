//! Rust code generator for polyplugc.
//!
//! Generates:
//! - Host-side: type-safe Rust wrappers to call plugins (for app developers)
//! - Guest-side: ABI entry point, allocator hookup, vtable stubs (for plugin developers)

use crate::error::CodegenError;
use crate::generators::CodeGenerator;
use crate::generators::GeneratedFile;
use crate::generators::GeneratedFiles;
use crate::ir::AbiBuiltin;
use crate::ir::PrimitiveType;
use crate::ir::ResolvedContract;
use crate::ir::ResolvedFunction;
use crate::ir::ResolvedType;
use crate::ir::ResolvedTypeRef;
use crate::ir::ValidatedIr;

/// The Rust code generator.
pub(crate) struct RustGenerator;

impl CodeGenerator for RustGenerator {
    fn language_name(&self) -> &'static str {
        "rust"
    }

    fn generate_host(
        &self,
        ir: &ValidatedIr,
        files: &mut GeneratedFiles,
    ) -> Result<(), CodegenError> {
        let mut out: String = String::new();
        out.push_str("// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n");
        out.push_str(
            "// Re-generate with: polyplugc generate --api api.toml --lang rust --out <dir>\n\n",
        );

        // Generate use statements
        out.push_str("use polyplug_runtime::abi::AbiError;\n");
        out.push_str("use polyplug_runtime::abi::PluginHandle;\n");
        out.push_str("use polyplug_runtime::registry::Registry;\n\n");

        // Generate user-defined types
        for ty in &ir.types {
            generate_rust_type(&mut out, ty);
        }

        // Generate contract caller structs
        for contract in &ir.contracts {
            generate_rust_host_contract(&mut out, contract)?;
        }

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("host_callers.rs"),
            content: out,
        });
        Ok(())
    }

    fn generate_guest(
        &self,
        ir: &ValidatedIr,
        files: &mut GeneratedFiles,
    ) -> Result<(), CodegenError> {
        let mut out: String = String::new();
        out.push_str("// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n");
        out.push_str("// Re-generate with: polyplugc generate --bundle bundle.toml --lang rust --out <dir>\n\n");

        out.push_str("use polyplug_runtime::abi::*;\n");
        out.push_str("use polyplug_runtime::allocator::polyplug_host_alloc;\n");
        out.push_str("use polyplug_runtime::allocator::polyplug_host_free;\n\n");

        // Global allocator hookup (routes plugin Rust allocs through host_alloc)
        out.push_str(GUEST_ALLOCATOR_TEMPLATE);

        // Generate vtable stubs for each contract in each plugin
        if let Some(ref bundle) = ir.bundle {
            for plugin in &bundle.plugins {
                out.push_str(&format!("// Plugin: {}\n", plugin.name));
                for contract_name in &plugin.implements {
                    // Find the contract in the IR (may not be present for guest-only gen)
                    out.push_str(&format!(
                        "// TODO: implement vtable for contract: {contract_name}\n"
                    ));
                }
            }
        }

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("guest_sdk.rs"),
            content: out,
        });
        Ok(())
    }
}

#[allow(dead_code)]
const GUEST_ALLOCATOR_TEMPLATE: &str = r#"
use std::alloc::{GlobalAlloc, Layout};

struct HostAllocator;

// SAFETY: host_alloc and host_free use the system allocator, which is thread-safe.
unsafe impl GlobalAlloc for HostAllocator {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        polyplug_host_alloc(layout.size(), layout.align())
    }
    unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
        polyplug_host_free(ptr, layout.size(), layout.align())
    }
}

#[global_allocator]
static ALLOCATOR: HostAllocator = HostAllocator;
"#;

fn generate_rust_type(out: &mut String, ty: &ResolvedType) {
    out.push_str(&format!("/// User-defined type `{}`\n", ty.name));
    out.push_str("#[repr(C)]\n");
    out.push_str("#[derive(Debug, Clone, Copy)]\n");
    out.push_str(&format!("pub struct {} {{\n", ty.name));
    for field in &ty.fields {
        out.push_str(&format!(
            "    pub {}: {},\n",
            field.name,
            rust_type_name(&field.ty)
        ));
    }
    out.push_str("}\n\n");
}

fn generate_rust_host_contract(
    out: &mut String,
    contract: &ResolvedContract,
) -> Result<(), CodegenError> {
    let struct_name: String = contract_name_to_struct(&contract.name);
    out.push_str(&format!(
        "/// Host caller for contract `{}` (id=0x{:016X})\n",
        contract.name, contract.contract_id
    ));
    out.push_str(&format!("pub struct {} {{\n", struct_name));
    out.push_str("    handle: PluginHandle,\n");
    out.push_str("    registry: &'static Registry,\n");
    out.push_str("}\n\n");

    out.push_str(&format!("impl {} {{\n", struct_name));
    for func in &contract.functions {
        generate_rust_host_fn(out, func, contract, &struct_name)?;
    }
    out.push_str("}\n\n");
    Ok(())
}

fn generate_rust_host_fn(
    out: &mut String,
    func: &ResolvedFunction,
    contract: &ResolvedContract,
    _struct_name: &str,
) -> Result<(), CodegenError> {
    out.push_str(&format!(
        "    /// Call `{}` (function_id={})\n",
        func.name, func.function_id
    ));
    out.push_str(&format!("    pub fn {}(&self", func.name));
    for param in &func.params {
        out.push_str(&format!(", {}: {}", param.name, rust_type_name(&param.ty)));
    }
    let return_type: String = func
        .returns
        .as_ref()
        .map(|r| format!(" -> {}", rust_type_name(r)))
        .unwrap_or_default();
    out.push_str(&format!("){return_type} {{\n"));
    out.push_str(&format!(
        "        // contract_id: 0x{:016X}\n",
        contract.contract_id
    ));
    out.push_str(&format!("        // function_id: {}\n", func.function_id));
    out.push_str("        todo!(\"implement\")\n");
    out.push_str("    }\n");
    Ok(())
}

fn rust_type_name(ty: &ResolvedTypeRef) -> String {
    match ty {
        ResolvedTypeRef::Primitive(p) => p.rust_name().to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => "StringView".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => "Buffer".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Ptr) => "*mut ()".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Void) => "()".to_owned(),
        ResolvedTypeRef::UserDefined(name) => name.clone(),
    }
}

fn contract_name_to_struct(name: &str) -> String {
    // Convert "image.decode" -> "ImageDecodeContract"
    name.split('.')
        .map(|p| {
            let mut chars: core::str::Chars<'_> = p.chars();
            match chars.next() {
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join("")
        + "Contract"
}

