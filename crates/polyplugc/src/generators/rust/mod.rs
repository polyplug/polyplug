// ─── Guest code generation helpers ────────────────────────────────────────────────

/// Generate the guest trait for one contract.
fn generate_guest_contract_trait(out: &mut String, contract: &ResolvedContract) {
    let trait_name: String = contract_name_to_guest_trait(&contract.name);
    out.push_str(&format!(
        "/// Guest trait for contract `{}` (id=0x{:016X})\n",
        contract.name, contract.contract_id
    ));
    out.push_str(&format!("pub trait {trait_name}: Send + Sync {{\n"));
    for func in &contract.functions {
        generate_guest_trait_method(out, func, &contract_name_to_struct(&contract.name));
    }
    out.push_str("}\n\n");
}

/// Emit one trait method line into the contracts.rs trait.
fn generate_guest_trait_method(out: &mut String, func: &ResolvedFunction, contract_struct: &str) {
    let ret_type: String = match &func.returns {
        Some(ty) => rust_type_name(ty),
        None => "()".to_owned(),
    };
    let sig_params: String = build_guest_trait_params(func, contract_struct);
    out.push_str(&format!(
        "    fn {}(&self{}) -> Result<{ret_type}, PluginError>;\n",
        func.name, sig_params
    ));
}

/// Build the trait method parameter list (after `&self`).
fn build_guest_trait_params(func: &ResolvedFunction, contract_struct: &str) -> String {
    if func.params.is_empty() {
        return String::new();
    }
    if func.params.len() == 1 {
        let param: &ResolvedParam = &func.params[0];
        return match &param.ty {
            ResolvedTypeRef::UserDefined(_) => {
                format!(", {}: &{}", param.name, rust_type_name(&param.ty))
            }
            _ => format!(", {}: {}", param.name, rust_type_name(&param.ty)),
        };
    }
    // Multiple primitive params — individual args
    let _ = contract_struct;
    func.params
        .iter()
        .map(|p: &ResolvedParam| format!(", {}: {}", p.name, rust_type_name(&p.ty)))
        .collect::<Vec<_>>()
        .join("")
}

/// Convert contract name to guest trait name, e.g. "test.add" -> "TestAddPlugin".
fn contract_name_to_guest_trait(name: &str) -> String {
    name.split('.')
        .map(|p: &str| {
            let mut chars: core::str::Chars<'_> = p.chars();
            match chars.next() {
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join("")
        + "Plugin"
}

/// Convert contract name to UPPER_SNAKE prefix, e.g. "test.add" -> "TEST_ADD".
fn contract_name_to_upper_snake(name: &str) -> String {
    name.replace('.', "_").to_uppercase()
}

/// Generate the full vtables.rs content.
fn generate_guest_vtables_file(out: &mut String, ir: &ValidatedIr) -> Result<(), CodegenError> {
    // Shared imports
    out.push_str("use std::sync::OnceLock;\n");
    out.push_str("use polyplug_guest::AbiError;\n");
    out.push_str("use polyplug_guest::PluginVTable;\n");
    out.push_str("use polyplug_guest::StringView;\n");
    out.push_str("#[allow(unused_imports)]\n");
    out.push_str("use polyplug_guest::{ABI_OK, ABI_ERROR_GENERIC, ABI_ERROR_PANIC};\n");
    out.push_str("use super::types::*;\n");
    for contract in &ir.contracts {
        let trait_name: String = contract_name_to_guest_trait(&contract.name);
        out.push_str(&format!("use super::contracts::{trait_name};\n"));
    }

    // FnPtr newtype — emitted once
    out.push_str("/// Wrapper for a function pointer stored in a static vtable array.\n");
    out.push_str("#[repr(transparent)]\n");
    out.push_str("pub struct FnPtr(pub *const ());\n");
    out.push_str("// SAFETY: FnPtr wraps a 'static function pointer. Function pointers are safe\n");
    out.push_str(
        "// to share across threads — the function itself handles its own synchronization.\n",
    );
    out.push_str("unsafe impl Send for FnPtr {}\n");
    out.push_str(
        "// SAFETY: Function pointers are inherently Sync — multiple threads may call the\n",
    );
    out.push_str(
        "// same function concurrently. The underlying data is read-only 'static memory.\n",
    );
    out.push_str("unsafe impl Sync for FnPtr {}\n\n");

    for contract in &ir.contracts {
        generate_guest_contract_vtable(out, contract)?;
    }

    Ok(())
}

/// Generate all vtable code for one contract.
fn generate_guest_contract_vtable(
    out: &mut String,
    contract: &ResolvedContract,
) -> Result<(), CodegenError> {
    let upper: String = contract_name_to_upper_snake(&contract.name);
    let struct_name: String = contract_name_to_struct(&contract.name);
    let trait_name: String = contract_name_to_guest_trait(&contract.name);
    let lower: String = contract.name.replace('.', "_");
    let fn_count: usize = contract.functions.len();

    // Contract ID constant
    out.push_str(&format!(
        "/// Contract ID constant -- pre-computed FNV-1a of \"{}@{}\".\n",
        contract.name, contract.version.major
    ));
    out.push_str(&format!(
        "pub(crate) const {upper}_CONTRACT_ID: u64 = 0x{:016X};\n\n",
        contract.contract_id
    ));

    // OnceLock for the trait object
    out.push_str(&format!(
        "pub(crate) static {upper}_IMPL: OnceLock<Box<dyn {trait_name}>> = OnceLock::new();\n\n"
    ));

    // ABI wrapper functions
    for func in &contract.functions {
        generate_guest_abi_wrapper(
            out,
            func,
            &lower,
            &upper,
            &struct_name,
            &trait_name,
            contract,
        )?;
    }

    // FnPtr array
    out.push_str(&format!(
        "static {upper}_FNS: [FnPtr; {fn_count}_usize] = [\n"
    ));
    for func in &contract.functions {
        out.push_str(&format!(
            "    FnPtr({lower}_{}_abi as *const ()),\n",
            func.name
        ));
    }
    out.push_str("];\n\n");

    // Static PluginVTable
    let minor: u32 = contract.version.minor;
    let patch: u32 = contract.version.patch;
    out.push_str(&format!(
        "pub(crate) static {upper}_VTABLE: PluginVTable = PluginVTable {{\n"
    ));
    out.push_str(&format!("    contract_id: {upper}_CONTRACT_ID,\n"));
    out.push_str(&format!(
        "    contract_version: {minor}_u32 << 16 | {patch}_u32,\n"
    ));
    out.push_str(&format!("    function_count: {fn_count}_u32,\n"));
    out.push_str(&format!(
        "    functions: {upper}_FNS.as_ptr() as *const *const (),\n"
    ));
    out.push_str("};\n\n");

    Ok(())
}

/// Generate one ABI wrapper function for a contract function.
fn generate_guest_abi_wrapper(
    out: &mut String,
    func: &ResolvedFunction,
    contract_lower: &str,
    contract_upper: &str,
    contract_struct: &str,
    trait_name: &str,
    _contract: &ResolvedContract,
) -> Result<(), CodegenError> {
    let wrapper_name: String = format!("{contract_lower}_{}_abi", func.name);
    let has_return: bool = func.returns.is_some();
    let out_param: &str = if has_return {
        "out: *mut ()"
    } else {
        "_out: *mut ()"
    };

    out.push_str(&format!(
        "/// ABI wrapper for {} (function_id = {}).\n",
        func.name, func.function_id
    ));
    out.push_str(
        "// SAFETY: args and out pointers are validated by the host runtime ABI contract.\n",
    );
    out.push_str(&format!(
        "extern \"C\" fn {wrapper_name}(args: *const (), {out_param}) -> AbiError {{\n"
    ));
    out.push_str("    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {\n");
    out.push_str(&format!(
        "        let impl_ref: &Box<dyn {trait_name}> = match {contract_upper}_IMPL.get() {{\n"
    ));
    out.push_str("            Some(i) => i,\n");
    out.push_str("            None => return AbiError { code: ABI_ERROR_GENERIC, message: StringView::null() },\n");
    out.push_str("        };\n");

    // Build the call expression
    emit_guest_wrapper_call(out, func, contract_struct);

    // Match on result
    if has_return {
        let ret_ty: String = match &func.returns {
            Some(ty) => rust_type_name(ty),
            None => String::new(),
        };
        out.push_str("        match result {\n");
        out.push_str("            Ok(val) => {\n");
        out.push_str(&format!(
            "                // SAFETY: out is a valid *mut {ret_ty} per ABI contract.\n"
        ));
        out.push_str(&format!(
            "                unsafe {{ std::ptr::write(out as *mut {ret_ty}, val); }}\n"
        ));
        out.push_str("                AbiError::ok()\n");
        out.push_str("            }\n");
        out.push_str(
            "            Err(e) => AbiError { code: e.code, message: StringView::null() },\n",
        );
        out.push_str("        }\n");
    } else {
        out.push_str("        match result {\n");
        out.push_str("            Ok(()) => AbiError::ok(),\n");
        out.push_str(
            "            Err(e) => AbiError { code: e.code, message: StringView::null() },\n",
        );
        out.push_str("        }\n");
    }

    out.push_str("    })) {\n");
    out.push_str("        Ok(err) => err,\n");
    out.push_str("        Err(_) => AbiError::panic_caught(),\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");

    Ok(())
}

/// Emit the trait call inside the ABI wrapper.
fn emit_guest_wrapper_call(out: &mut String, func: &ResolvedFunction, contract_struct: &str) {
    if func.params.is_empty() {
        out.push_str("        // SAFETY: no args for this function.\n");
        out.push_str("        let _ = args;\n");
        out.push_str(&format!("        let result = impl_ref.{}();\n", func.name));
        return;
    }
    if func.params.len() == 1 {
        let param: &ResolvedParam = &func.params[0];
        match &param.ty {
            ResolvedTypeRef::UserDefined(_) => {
                let ty_name: String = rust_type_name(&param.ty);
                out.push_str(&format!(
                    "        // SAFETY: args is a valid *const {ty_name} per ABI contract.\n"
                ));
                out.push_str(&format!(
                    "        let result = impl_ref.{}(unsafe {{ &*(args as *const {ty_name}) }});\n",
                    func.name
                ));
            }
            _ => {
                let ty_name: String = rust_type_name(&param.ty);
                out.push_str(&format!(
                    "        // SAFETY: args is a valid *const {ty_name} per ABI contract.\n"
                ));
                out.push_str(&format!(
                    "        let result = impl_ref.{}(unsafe {{ *(args as *const {ty_name}) }});\n",
                    func.name
                ));
            }
        }
        return;
    }
    // Multiple params — unpack arg-pack struct
    let pack_struct: String = arg_pack_struct_name(contract_struct, &func.name);
    out.push_str(&format!(
        "        // SAFETY: args is a valid *const {pack_struct} per ABI contract.\n"
    ));
    out.push_str(&format!(
        "        let packed: &{pack_struct} = unsafe {{ &*(args as *const {pack_struct}) }};\n"
    ));
    let call_args: String = func
        .params
        .iter()
        .map(|p: &ResolvedParam| format!("packed.{}", p.name))
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str(&format!(
        "        let result = impl_ref.{}({call_args});\n",
        func.name
    ));
}

/// Generate the init.rs file content.
fn generate_guest_init_file(out: &mut String, ir: &ValidatedIr) {
    let has_trace: bool = ir
        .bundle
        .as_ref()
        .is_some_and(|b: &crate::ir::ResolvedBundle| {
            b.plugins
                .iter()
                .any(|p: &crate::ir::ResolvedPlugin| p.optional.contains(&"trace".to_owned()))
        });
    out.push_str("use polyplug_guest::AbiError;\n");
    out.push_str("use polyplug_guest::ABI_OK;\n");
    out.push_str("use polyplug_guest::ABI_ERROR_GENERIC;\n");
    out.push_str("use polyplug_guest::PluginDescriptor;\n");
    out.push_str("use polyplug_guest::PluginRegistrar;\n");
    out.push_str("use polyplug_guest::PluginVTable;\n");
    out.push_str("use polyplug_guest::StringView;\n");
    for contract in &ir.contracts {
        let upper: String = contract_name_to_upper_snake(&contract.name);
        out.push_str(&format!("use super::vtables::{upper}_CONTRACT_ID;\n"));
        out.push_str(&format!("use super::vtables::{upper}_VTABLE;\n"));
    }
    out.push('\n');

    out.push_str("#[unsafe(no_mangle)]\n");
    out.push_str("pub extern \"C\" fn polyplug_abi_version() -> u32 { 1 }\n\n");

    out.push_str("/// Register all plugin vtables with the host.\n");
    out.push_str("///\n");
    out.push_str("/// # Safety\n");
    out.push_str("/// `registrar` must be a valid non-null pointer to a PluginRegistrar.\n");
    out.push_str("#[unsafe(no_mangle)]\n");
    out.push_str(
        "pub unsafe extern \"C\" fn polyplug_init(registrar: *mut PluginRegistrar) -> AbiError {\n",
    );
    out.push_str("    if registrar.is_null() {\n");
    out.push_str(
        "        return AbiError { code: ABI_ERROR_GENERIC, message: StringView::null() };\n",
    );
    out.push_str("    }\n");
    out.push_str("    // SAFETY: registrar is non-null and valid per ABI contract.\n");
    out.push_str("    let reg: &mut PluginRegistrar = unsafe { &mut *registrar };\n\n");
    if has_trace {
        out.push_str("    // Optional: trace extension\n");
        out.push_str("    const EXT_TRACE_ID: u32 = 0xC4EB9AEE_u32;\n");
        out.push_str("    // SAFETY: reg.host is a valid HostVTable pointer set by the host.\n");
        out.push_str("    let trace_vtable_ptr: *const () = unsafe { ((*reg.host).get_extension)(EXT_TRACE_ID) };\n");
        out.push_str("    if trace_vtable_ptr.is_null() {\n");
        out.push_str("        // Trace extension not available — continue without tracing.\n");
        out.push_str("    }\n\n");
    }

    for contract in &ir.contracts {
        let upper: String = contract_name_to_upper_snake(&contract.name);
        let plugin_name: String = contract.name.replace('.', "_") + "_plugin";
        let plugin_name_len: usize = plugin_name.len();
        let contract_name: &str = &contract.name;
        let contract_name_len: usize = contract_name.len();
        let major: u32 = contract.version.major;
        let minor: u32 = contract.version.minor;
        let patch: u32 = contract.version.patch;

        out.push_str(&format!(
            "    let desc_{upper}: PluginDescriptor = PluginDescriptor {{\n"
        ));
        out.push_str(&format!(
            "        name: StringView {{ ptr: b\"{plugin_name}\".as_ptr(), len: {plugin_name_len}_usize }},\n"
        ));
        out.push_str(&format!(
            "        contract_name: StringView {{ ptr: b\"{contract_name}\".as_ptr(), len: {contract_name_len}_usize }},\n"
        ));
        out.push_str(&format!("        version_major: {major}_u32,\n"));
        out.push_str(&format!("        version_minor: {minor}_u32,\n"));
        out.push_str(&format!("        version_patch: {patch}_u32,\n"));
        out.push_str("    };\n");
        out.push_str("    // SAFETY: desc and vtable are 'static.\n");
        out.push_str(&format!("    let err_{upper}: AbiError = unsafe {{\n"));
        out.push_str(&format!(
            "        (reg.register_plugin)(registrar, &desc_{upper} as *const PluginDescriptor, &{upper}_VTABLE as *const PluginVTable)\n"
        ));
        out.push_str("    };\n");
        out.push_str(&format!("    if err_{upper}.code != ABI_OK {{\n"));
        out.push_str(&format!("        return err_{upper};\n"));
        out.push_str("    }\n\n");
    }

    out.push_str("    AbiError::ok()\n");
    out.push_str("}\n");
}

