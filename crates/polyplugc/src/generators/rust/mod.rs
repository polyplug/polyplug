/// Returns true when a function's params require an arg-pack struct
/// (i.e. 2+ primitive params, or any mix that isn't a single UserDefined param).
fn needs_arg_pack(params: &[ResolvedParam]) -> bool {
    if params.len() <= 1 {
        return false;
    }
    // Multiple params always need packing.
    true
}

/// Emit a `#[repr(C)]` arg-pack struct for a multi-param function into `types.rs`.
fn emit_arg_pack_struct(out: &mut String, contract_struct: &str, func: &ResolvedFunction) {
    let struct_name: String = arg_pack_struct_name(contract_struct, &func.name);
    out.push_str(&format!(
        "/// Auto-generated arg-pack for `{contract_struct}::{}`\n",
        func.name
    ));
    out.push_str("#[repr(C)]\n");
    out.push_str("#[derive(Debug, Clone, Copy)]\n");
    out.push_str(&format!("pub struct {struct_name} {{\n"));
    for param in &func.params {
        out.push_str(&format!(
            "    pub {}: {},\n",
            param.name,
            rust_type_name(&param.ty)
        ));
    }
    out.push_str("}\n\n");
}

/// Generate the PascalCase arg-pack struct name for a function.
/// e.g. "TestAddContract" + "add_primitive" → "TestAddContractAddPrimitiveArgs"
fn arg_pack_struct_name(contract_struct: &str, fn_name: &str) -> String {
    let fn_pascal: String = fn_name
        .split('_')
        .map(|seg: &str| {
            let mut chars: core::str::Chars<'_> = seg.chars();
            match chars.next() {
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join("");
    format!("{contract_struct}{fn_pascal}Args")
}

fn dep_contract_name(dep: &ResolvedDependency) -> &str {
    match dep {
        ResolvedDependency::ByContract { contract, .. } => contract,
        ResolvedDependency::ByBundle { contract, .. } => contract,
    }
}

fn dep_contract_id(dep: &ResolvedDependency) -> u64 {
    match dep {
        ResolvedDependency::ByContract { contract_id, .. } => *contract_id,
        ResolvedDependency::ByBundle { contract_id, .. } => *contract_id,
    }
}

fn dep_min_version(dep: &ResolvedDependency) -> u32 {
    match dep {
        ResolvedDependency::ByContract { min_version, .. } => *min_version,
        ResolvedDependency::ByBundle { min_version, .. } => *min_version,
    }
}

/// Generate the full caller struct + impl for one contract.
fn generate_host_contract_caller(
    out: &mut String,
    contract: &ResolvedContract,
) -> Result<(), CodegenError> {
    let struct_name: String = contract_name_to_struct(&contract.name);

    out.push_str(&format!(
        "/// Host caller for contract `{}` (id=0x{:016X})\n",
        contract.name, contract.contract_id
    ));
    out.push_str(&format!("pub struct {struct_name} {{\n"));
    out.push_str("    handle: PluginHandle,\n");
    out.push_str("    runtime: &'static Runtime,\n");
    out.push_str("}\n\n");

    out.push_str(&format!("impl {struct_name} {{\n"));
    out.push_str(&format!(
        "    pub fn new(handle: PluginHandle, runtime: &'static Runtime) -> {struct_name} {{\n"
    ));
    out.push_str(&format!("        {struct_name} {{ handle, runtime }}\n"));
    out.push_str("    }\n\n");

    for func in &contract.functions {
        generate_host_fn_caller(out, func, contract, &struct_name)?;
    }

    out.push_str("}\n\n");
    Ok(())
}

/// Generate a single caller method for one contract function.
fn generate_host_fn_caller(
    out: &mut String,
    func: &ResolvedFunction,
    _contract: &ResolvedContract,
    contract_struct: &str,
) -> Result<(), CodegenError> {
    let fn_id: u32 = func.function_id;

    // Build parameter list for the Rust signature
    let sig_params: String = build_sig_params(func, contract_struct);

    // Build return type
    let ret_type: String = match &func.returns {
        Some(ty) => rust_type_name(ty),
        None => "()".to_owned(),
    };

    out.push_str(&format!(
        "    /// Call `{}` (function_id={})\n",
        func.name, fn_id
    ));
    out.push_str(&format!(
        "    pub fn {}(&self{}) -> Result<{ret_type}, PluginError> {{\n",
        func.name, sig_params
    ));

    // args setup
    emit_args_setup(out, func, contract_struct);

    // out setup
    emit_out_setup(out, &func.returns);

    // The unsafe call
    let out_arg: &str = if func.returns.is_some() {
        "&mut out_val as *mut {ret_ty} as *mut ()"
    } else {
        "core::ptr::null_mut()"
    };

    let param_ty_comment: String = args_type_comment(func, contract_struct);
    let ret_ty_comment: String = ret_type.clone();

    out.push_str(&format!(
        "        // SAFETY: args_ptr points to a valid {param_ty_comment} and out_ptr to a valid {ret_ty_comment}.\n"
    ));
    out.push_str("        // Enforced by the generated caller contract.\n");
    out.push_str("        let out_ptr: *mut () = ");
    if func.returns.is_some() {
        out.push_str(&format!("&mut out_val as *mut {ret_type} as *mut ();\n"));
    } else {
        out.push_str("core::ptr::null_mut();\n");
    }
    out.push_str("        let vtable_ptr: *const PluginVTable = match self.runtime.resolve_plugin(self.handle) {\n");
    out.push_str("            Ok(ptr) => ptr,\n");
    out.push_str("            Err(err) => {\n");
    out.push_str("                let code: u32 = match err {\n");
    out.push_str("                    polyplug::error::RegistryError::StaleHandle { .. } => ABI_ERROR_STALE_HANDLE,\n");
    out.push_str("                    polyplug::error::RegistryError::PluginNotFound { .. } => ABI_ERROR_NOT_FOUND,\n");
    out.push_str("                    polyplug::error::RegistryError::ContractIdCollision { .. } | polyplug::error::RegistryError::DuplicateProvider { .. } => ABI_ERROR_GENERIC,\n");
    out.push_str("                };\n");
    out.push_str("                return Err(PluginError { code, message: String::new() });\n");
    out.push_str("            }\n");
    out.push_str("        };\n");
    out.push_str("        if vtable_ptr.is_null() {\n");
    out.push_str("            return Err(PluginError { code: ABI_ERROR_NOT_FOUND, message: String::new() });\n");
    out.push_str("        }\n");
    out.push_str("        // SAFETY: vtable_ptr is valid for the duration of the call; args_ptr/out_ptr match the ABI contract.\n");
    out.push_str("        let err: AbiError = unsafe {\n");
    out.push_str("            let vtable: &PluginVTable = &*vtable_ptr;\n");
    out.push_str(&format!(
        "            if {fn_id}_u32 >= vtable.function_count {{\n"
    ));
    out.push_str("                AbiError { code: ABI_FUNCTION_NOT_AVAIL, message: polyplug::abi::StringView::null() }\n");
    out.push_str("            } else {\n");
    out.push_str(&format!(
        "                let fn_ptr: *const () = *vtable.functions.add({fn_id}_usize);\n"
    ));
    out.push_str("                let dispatch_fn: unsafe extern \"C\" fn(*const (), *mut ()) -> AbiError = core::mem::transmute(fn_ptr);\n");
    out.push_str("                dispatch_fn(args_ptr, out_ptr)\n");
    out.push_str("            }\n");
    out.push_str("        };\n");
    out.push_str("        if err.code != ABI_OK {\n");
    out.push_str(
        "            return Err(PluginError { code: err.code, message: String::new() });\n",
    );
    out.push_str("        }\n");

    // Return
    if func.returns.is_some() {
        out.push_str("        Ok(out_val)\n");
    } else {
        out.push_str("        Ok(())\n");
    }

    let _ = out_arg; // suppress unused warning
    out.push_str("    }\n\n");
    Ok(())
}

/// Build the parameter portion of the Rust function signature (after `&self`).
/// Returns a string starting with `, ` if there are params, else empty.
fn build_sig_params(func: &ResolvedFunction, contract_struct: &str) -> String {
    if func.params.is_empty() {
        return String::new();
    }
    if func.params.len() == 1 {
        let param: &ResolvedParam = &func.params[0];
        let ty: &ResolvedTypeRef = &param.ty;
        return match ty {
            ResolvedTypeRef::UserDefined(_) => {
                format!(", {}: &{}", param.name, rust_type_name(ty))
            }
            _ => format!(", {}: {}", param.name, rust_type_name(ty)),
        };
    }
    // Multiple params: individual args (will be packed in body)
    let params_str: String = func
        .params
        .iter()
        .map(|p: &ResolvedParam| format!(", {}: {}", p.name, rust_type_name(&p.ty)))
        .collect::<Vec<_>>()
        .join("");
    let _ = contract_struct; // used elsewhere
    params_str
}

/// Emit the `args_ptr` setup lines into the function body.
fn emit_args_setup(out: &mut String, func: &ResolvedFunction, contract_struct: &str) {
    if func.params.is_empty() {
        out.push_str("        let args_ptr: *const () = core::ptr::null();\n");
        return;
    }
    if func.params.len() == 1 {
        let param: &ResolvedParam = &func.params[0];
        let ty_name: String = rust_type_name(&param.ty);
        match &param.ty {
            ResolvedTypeRef::UserDefined(_) => {
                out.push_str(&format!(
                    "        let args_ptr: *const () = {name} as *const {ty} as *const ();\n",
                    name = param.name,
                    ty = ty_name,
                ));
            }
            _ => {
                out.push_str(&format!(
                    "        let {name}_val: {ty} = {name};\n",
                    name = param.name,
                    ty = ty_name,
                ));
                out.push_str(&format!(
                    "        let args_ptr: *const () = &{name}_val as *const {ty} as *const ();\n",
                    name = param.name,
                    ty = ty_name,
                ));
            }
        }
        return;
    }
    // Multiple params: pack into arg-pack struct
    let pack_struct: String = arg_pack_struct_name(contract_struct, &func.name);
    out.push_str(&format!(
        "        let args_val: {pack_struct} = {pack_struct} {{\n"
    ));
    for param in &func.params {
        out.push_str(&format!("            {}: {},\n", param.name, param.name));
    }
    out.push_str("        };\n");
    out.push_str(&format!(
        "        let args_ptr: *const () = &args_val as *const {pack_struct} as *const ();\n"
    ));
}

/// Emit the `out_val` / `out_ptr` setup (only when there is a return type).
fn emit_out_setup(out: &mut String, returns: &Option<ResolvedTypeRef>) {
    if let Some(ret_ty) = returns {
        let ty_name: String = rust_type_name(ret_ty);
        out.push_str(&format!(
            "        let mut out_val: {ty_name} = unsafe {{ core::mem::zeroed() }};\n"
        ));
    }
}

/// Return a human-readable string describing the args type for SAFETY comments.
fn args_type_comment(func: &ResolvedFunction, contract_struct: &str) -> String {
    if func.params.is_empty() {
        return "()".to_owned();
    }
    if func.params.len() == 1 {
        return rust_type_name(&func.params[0].ty);
    }
    arg_pack_struct_name(contract_struct, &func.name)
}

