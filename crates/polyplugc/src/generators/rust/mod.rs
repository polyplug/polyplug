use crate::ir::ValidatedIr;

/// The Rust code generator.
pub(crate) struct RustGenerator;

impl CodeGenerator for RustGenerator {
    fn language_name(&self) -> &'static str {
        "rust"
    }

    fn generate_host(
        &self,
        ir: &ValidatedIr,
        files: &mut GeneratedFiles,
    ) -> Result<(), CodegenError> {
        let header: &str = "// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n\
            // Re-generate with: polyplugc generate --api api.toml --lang rust --out <dir>\n\
            #![allow(unused_imports)]\n\n";

        // ── types.rs ──────────────────────────────────────────────────────────
        let mut types_out: String = String::new();
        types_out.push_str(header);

        // Emit user-defined types from IR
        for ty in &ir.types {
            generate_rust_type(&mut types_out, ty);
        }

        // Emit generated arg-pack structs for multi-primitive-param functions
        for contract in &ir.contracts {
            let struct_name: String = contract_name_to_struct(&contract.name);
            for func in &contract.functions {
                if needs_arg_pack(&func.params) {
                    emit_arg_pack_struct(&mut types_out, &struct_name, func);
                }
            }
        }

        if let Some(ref bundle) = ir.bundle {
            types_out.push_str(&format!(
                "pub const MY_BUNDLE_ID: u64 = {};\n\n",
                bundle.bundle_id
            ));
            for dep in &bundle.dependencies {
                let contract_upper: String = dep_contract_name(dep)
                    .to_uppercase()
                    .replace(['.', '-'], "_");
                types_out.push_str(&format!(
                    "pub const DEP_{contract_upper}: u64 = {};\n",
                    dep_contract_id(dep)
                ));
                types_out.push_str(&format!(
                    "pub const DEP_{contract_upper}_MIN_VERSION: u32 = {};\n",
                    dep_min_version(dep)
                ));
            }
            types_out.push('\n');
        }

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("host/types.rs"),
            content: types_out,
        });

        // ── host_callers.rs ───────────────────────────────────────────────────
        let mut callers_out: String = String::new();
        callers_out.push_str(header);

        callers_out.push_str("use polyplug_guest::PluginError;\n");
        callers_out.push_str("use polyplug::abi::ABI_OK;\n");
        callers_out.push_str("use polyplug::abi::AbiError;\n");
        callers_out.push_str("use polyplug::abi::PluginVTable;\n");
        callers_out.push_str("use polyplug::abi::ABI_ERROR_GENERIC;\n");
        callers_out.push_str("use polyplug::abi::ABI_ERROR_NOT_FOUND;\n");
        callers_out.push_str("use polyplug::abi::ABI_ERROR_STALE_HANDLE;\n");
        callers_out.push_str("use polyplug::abi::ABI_FUNCTION_NOT_AVAIL;\n");
        callers_out.push_str("use polyplug::abi::PluginHandle;\n");
        callers_out.push_str("use polyplug::runtime::Runtime;\n");
        callers_out.push_str("use super::types::*;\n\n");

        for contract in &ir.contracts {
            generate_host_contract_caller(&mut callers_out, contract)?;
        }

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("host/host_callers.rs"),
            content: callers_out,
        });

        // ── manifest.toml ─────────────────────────────────────────────────────
        let manifest_content: String = [
            "# THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n",
            "[manifest]\n",
            "schema_version = 1\n",
            "lang = \"rust\"\n",
            "generated_by = \"polyplugc\"\n",
        ]
        .concat();

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("manifest.toml"),
            content: manifest_content,
        });

        Ok(())
    }

    fn generate_guest(
        &self,
        ir: &ValidatedIr,
        files: &mut GeneratedFiles,
    ) -> Result<(), CodegenError> {
        let header: &str = "// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n\
            // Re-generate with: polyplugc generate --api api.toml --lang rust --out <dir>\n\
            #![allow(unused_imports)]\n\n";

        // ── types.rs ──────────────────────────────────────────────────────────
        let mut types_out: String = String::new();
        types_out.push_str(header);

        for ty in &ir.types {
            generate_rust_type(&mut types_out, ty);
        }

        for contract in &ir.contracts {
            let struct_name: String = contract_name_to_struct(&contract.name);
            for func in &contract.functions {
                if needs_arg_pack(&func.params) {
                    emit_arg_pack_struct(&mut types_out, &struct_name, func);
                }
            }
        }

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("guest/types.rs"),
            content: types_out,
        });

        // ── contracts.rs ──────────────────────────────────────────────────────
        let mut contracts_out: String = String::new();
        contracts_out.push_str(header);
        contracts_out.push_str("use polyplug_guest::PluginError;\n");
        contracts_out.push_str("use polyplug_guest::StringView;\n");
        contracts_out.push_str("use super::types::*;\n\n");

        for contract in &ir.contracts {
            generate_guest_contract_trait(&mut contracts_out, contract);
        }

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("guest/contracts.rs"),
            content: contracts_out,
        });

        // ── vtables.rs ────────────────────────────────────────────────────────
        let mut vtables_out: String = String::new();
        vtables_out.push_str(header);
        generate_guest_vtables_file(&mut vtables_out, ir)?;

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("guest/vtables.rs"),
            content: vtables_out,
        });

        // ── init.rs ───────────────────────────────────────────────────────────
        let mut init_out: String = String::new();
        init_out.push_str(header);
        generate_guest_init_file(&mut init_out, ir);

        files.files.push(GeneratedFile {
            path: std::path::PathBuf::from("guest/init.rs"),
            content: init_out,
        });

        // --api: manifest already emitted by generate_host(); --bundle: emit full discovery manifest
        if ir.bundle.is_some() {
            let manifest_content: String = generate_bundle_manifest(ir);
            files.files.push(GeneratedFile {
                path: std::path::PathBuf::from("manifest.toml"),
                content: manifest_content,
            });
        }
        // When ir.bundle.is_none() (--api mode): NO manifest emitted here.
        // The root manifest.toml was already emitted by generate_host().
        Ok(())
    }
}

/// Generate a full discovery `manifest.toml` for `--bundle` invocations.
/// Called only when `ir.bundle.is_some()`.
fn generate_bundle_manifest(ir: &ValidatedIr) -> String {
    let bundle: &ResolvedBundle = match ir.bundle.as_ref() {
        Some(b) => b,
        None => return String::from("# ERROR: bundle manifest called without bundle IR\n"),
    };

    let name: &str = &bundle.name;
    let version: String = format!(
        "{}.{}.{}",
        bundle.version.major, bundle.version.minor, bundle.version.patch
    );
    let file: String = format!("lib{}.so", bundle.name);

    // Collect provides: all implements from all plugins, deduplicated
    let mut provides: Vec<String> = bundle
        .plugins
        .iter()
        .flat_map(|p: &ResolvedPlugin| p.implements.iter().cloned())
        .collect();
    provides.sort();
    provides.dedup();

    // Build TOML string arrays (keys with @ must be quoted)
    let provides_toml: String = if provides.is_empty() {
        String::from("[]")
    } else {
        format!(
            "[{}]",
            provides
                .iter()
                .map(|s: &String| format!("\"{}\"", s))
                .collect::<Vec<_>>()
                .join(", ")
        )
    };

    // Build function_count inline table: { "name@major" = count }
    let fn_count_entries: Vec<String> = ir
        .contracts
        .iter()
        .map(|c: &ResolvedContract| {
            let fn_count: u32 = c.functions.len() as u32;
            format!("\"{}@{}\" = {}", c.name, c.version.major, fn_count)
        })
        .collect();
    let function_count_toml: String = format!("{{ {} }}", fn_count_entries.join(", "));

    let mut dep_toml: String = String::new();
    for dep in &bundle.dependencies {
        dep_toml.push_str("\n[[dependency]]\n");
        match dep {
            ResolvedDependency::ByContract {
                contract,
                min_version,
                ..
            } => {
                dep_toml.push_str("kind = \"contract\"\n");
                dep_toml.push_str(&format!("contract = \"{contract}\"\n"));
                dep_toml.push_str(&format!("min_version = \"{min_version}.0\"\n"));
            }
            ResolvedDependency::ByBundle {
                bundle,
                contract,
                min_version,
                ..
            } => {
                dep_toml.push_str("kind = \"bundle\"\n");
                dep_toml.push_str(&format!("bundle = \"{bundle}\"\n"));
                dep_toml.push_str(&format!("contract = \"{contract}\"\n"));
                dep_toml.push_str(&format!("min_version = \"{min_version}.0\"\n"));
            }
        }
    }

    format!(
        "# THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n\
         name = \"{name}\"\n\
         version = \"{version}\"\n\
         runtime = \"native\"\n\
         file = \"{file}\"\n\
         provides = {provides_toml}\n\
         function_count = {function_count_toml}\n\
         {dep_toml}"
    )
}

