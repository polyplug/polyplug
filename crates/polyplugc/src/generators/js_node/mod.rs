use std::collections::BTreeSet;
use std::path::PathBuf;

use crate::error::CodegenError;
use crate::generators::CodeGenerator;
use crate::generators::GeneratedFile;
use crate::generators::GeneratedFiles;
use crate::ir::AbiBuiltin;
use crate::ir::PrimitiveType;
use crate::ir::ResolvedFunction;
use crate::ir::ResolvedParam;
use crate::ir::ResolvedType;
use crate::ir::ResolvedTypeRef;
use crate::ir::ValidatedIr;

pub(crate) struct JsNodeGenerator {
    pub(crate) typescript_mode: bool,
}

const TS_HEADER: &str = "// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n\
// Re-generate with: polyplugc generate --api api.toml --lang ts-node --out <dir>\n\n";

const JS_HEADER: &str = "// THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n\
// Re-generate with: polyplugc generate --api api.toml --lang js-node --out <dir>\n\
// @ts-check\n\n";

impl CodeGenerator for JsNodeGenerator {
    fn language_name(&self) -> &'static str {
        if self.typescript_mode {
            "ts-node"
        } else {
            "js-node"
        }
    }

    fn generate_host(
        &self,
        ir: &ValidatedIr,
        files: &mut GeneratedFiles,
    ) -> Result<(), CodegenError> {
        let ext: &str = file_extension(self.typescript_mode);
        let types_content: String = generate_types_file(ir, self.typescript_mode);
        let callers_content: String = generate_host_callers_file(ir, self.typescript_mode);

        files.files.push(GeneratedFile {
            path: PathBuf::from(format!("host/types.{ext}")),
            content: types_content,
        });
        files.files.push(GeneratedFile {
            path: PathBuf::from(format!("host/callers.{ext}")),
            content: callers_content,
        });

        Ok(())
    }

    fn generate_guest(
        &self,
        ir: &ValidatedIr,
        files: &mut GeneratedFiles,
    ) -> Result<(), CodegenError> {
        let ext: &str = file_extension(self.typescript_mode);
        let types_content: String = generate_types_file(ir, self.typescript_mode);
        let contracts_content: String = generate_guest_contracts_file(ir, self.typescript_mode);

        files.files.push(GeneratedFile {
            path: PathBuf::from(format!("guest/types.{ext}")),
            content: types_content,
        });
        files.files.push(GeneratedFile {
            path: PathBuf::from(format!("guest/contracts.{ext}")),
            content: contracts_content,
        });

        if ir.bundle.is_some() {
            let manifest_content: String = format!(
                "# THIS FILE IS AUTO-GENERATED BY polyplugc. DO NOT EDIT.\n\
runtime = \"{}\"\n",
                self.language_name()
            );
            files.files.push(GeneratedFile {
                path: PathBuf::from("manifest.toml"),
                content: manifest_content,
            });
        }

        Ok(())
    }
}

fn file_extension(typescript_mode: bool) -> &'static str {
    if typescript_mode { "ts" } else { "js" }
}

fn file_header(typescript_mode: bool) -> &'static str {
    if typescript_mode {
        TS_HEADER
    } else {
        JS_HEADER
    }
}

fn generate_types_file(ir: &ValidatedIr, typescript_mode: bool) -> String {
    let mut out: String = String::new();
    out.push_str(file_header(typescript_mode));

    let uses_string_view: bool = uses_builtin(ir, AbiBuiltin::StringView);
    let uses_buffer: bool = uses_builtin(ir, AbiBuiltin::Buffer);
    if typescript_mode {
        if uses_string_view || uses_buffer {
            let mut imports: Vec<&str> = Vec::new();
            if uses_string_view {
                imports.push("StringView");
            }
            if uses_buffer {
                imports.push("Buffer");
            }
            let joined: String = imports.join(", ");
            out.push_str(&format!(
                "export type {{ {joined} }} from \"../polyplug-guest\";\n\n"
            ));
        }
    } else {
        if uses_string_view {
            out.push_str("/** @typedef {import(\"../polyplug-guest\").StringView} StringView */\n");
        }
        if uses_buffer {
            out.push_str("/** @typedef {import(\"../polyplug-guest\").Buffer} Buffer */\n");
        }
        if uses_string_view || uses_buffer {
            out.push('\n');
        }
    }

    for ty in &ir.types {
        if typescript_mode {
            emit_ts_user_type(&mut out, ty);
        } else {
            emit_js_user_type(&mut out, ty);
        }
        out.push('\n');
    }

    if !typescript_mode {
        let exports: BTreeSet<String> = collect_js_exports(ir, uses_string_view, uses_buffer);
        if !exports.is_empty() {
            out.push_str("module.exports = {\n");
            for name in exports {
                out.push_str(&format!("    {}: undefined,\n", name));
            }
            out.push_str("};\n");
        }
    }

    out
}

fn generate_host_callers_file(ir: &ValidatedIr, typescript_mode: bool) -> String {
    let mut out: String = String::new();
    out.push_str(file_header(typescript_mode));

    emit_type_imports(&mut out, ir, typescript_mode, "./types");

    for contract in &ir.contracts {
        let struct_name: String = contract_name_to_struct(&contract.name);
        let caller_name: String = format!("{struct_name}Caller");
        if typescript_mode {
            out.push_str(&format!("export class {caller_name} {{\n"));
        } else {
            out.push_str(&format!("class {caller_name} {{\n"));
        }
        out.push_str("    constructor() {}\n\n");
        for func in &contract.functions {
            emit_host_caller_method(&mut out, func, typescript_mode);
        }
        out.push_str("}\n\n");
        if !typescript_mode {
            out.push_str(&format!(
                "module.exports.{caller_name} = {caller_name};\n\n"
            ));
        }
    }

    out
}

fn generate_guest_contracts_file(ir: &ValidatedIr, typescript_mode: bool) -> String {
    let mut out: String = String::new();
    out.push_str(file_header(typescript_mode));

    emit_type_imports(&mut out, ir, typescript_mode, "./types");

    for contract in &ir.contracts {
        let trait_name: String = contract_name_to_guest_trait(&contract.name);
        if typescript_mode {
            out.push_str(&format!("export abstract class {trait_name} {{\n"));
        } else {
            out.push_str(&format!("/** @abstract */\nclass {trait_name} {{\n"));
        }
        for func in &contract.functions {
            emit_guest_contract_method(&mut out, func, typescript_mode);
        }
        out.push_str("}\n\n");
        if !typescript_mode {
            out.push_str(&format!("module.exports.{trait_name} = {trait_name};\n\n"));
        }
    }

    out
}

fn emit_type_imports(out: &mut String, ir: &ValidatedIr, typescript_mode: bool, module_path: &str) {
    let imports: BTreeSet<String> = collect_type_imports(ir);
    if imports.is_empty() {
        return;
    }
    if typescript_mode {
        let joined: String = imports.into_iter().collect::<Vec<String>>().join(", ");
        out.push_str(&format!(
            "import type {{ {joined} }} from \"{module_path}\";\n\n"
        ));
    } else {
        for name in imports {
            out.push_str(&format!(
                "/** @typedef {{import(\"{module_path}\").{name}}} {name} */\n"
            ));
        }
        out.push('\n');
    }
}

fn emit_ts_user_type(out: &mut String, ty: &ResolvedType) {
    out.push_str(&format!("export interface {} {{\n", ty.name));
    for field in &ty.fields {
        let field_ty: String = ts_type_name(&field.ty);
        out.push_str(&format!("    {}: {};\n", field.name, field_ty));
    }
    out.push_str("}\n");
}

fn emit_js_user_type(out: &mut String, ty: &ResolvedType) {
    out.push_str(&format!("/** @typedef {{Object}} {}\n", ty.name));
    for field in &ty.fields {
        let field_ty: String = ts_type_name(&field.ty);
        out.push_str(&format!(" * @property {{{}}} {}\n", field_ty, field.name));
    }
    out.push_str(" */\n");
}

fn emit_host_caller_method(out: &mut String, func: &ResolvedFunction, typescript_mode: bool) {
    let sig_params: String = build_sig_params(func, typescript_mode);
    let ret_type: String = ts_return_type(&func.returns);
    if typescript_mode {
        out.push_str(&format!(
            "    {}({}) : {} {{\n",
            func.name, sig_params, ret_type
        ));
        out.push_str(&format!(
            "        throw new Error(\"TODO: implement host caller {}\");\n",
            func.name
        ));
    } else {
        emit_js_doc_signature(out, func, &ret_type);
        out.push_str(&format!("    {}({}) {{\n", func.name, sig_params));
        out.push_str(&format!(
            "        throw new Error(\"TODO: implement host caller {}\");\n",
            func.name
        ));
    }
    out.push_str("    }\n\n");
}

fn emit_guest_contract_method(out: &mut String, func: &ResolvedFunction, typescript_mode: bool) {
    let sig_params: String = build_sig_params(func, typescript_mode);
    let ret_type: String = ts_return_type(&func.returns);
    if typescript_mode {
        out.push_str(&format!(
            "    {}({}) : {} {{\n",
            func.name, sig_params, ret_type
        ));
        out.push_str(&format!(
            "        throw new Error(\"TODO: implement guest contract {}\");\n",
            func.name
        ));
    } else {
        emit_js_doc_signature(out, func, &ret_type);
        out.push_str(&format!("    {}({}) {{\n", func.name, sig_params));
        out.push_str(&format!(
            "        throw new Error(\"TODO: implement guest contract {}\");\n",
            func.name
        ));
    }
    out.push_str("    }\n\n");
}

fn emit_js_doc_signature(out: &mut String, func: &ResolvedFunction, ret_type: &str) {
    out.push_str("    /**\n");
    for param in &func.params {
        let param_ty: String = ts_type_name(&param.ty);
        out.push_str(&format!("     * @param {{{}}} {}\n", param_ty, param.name));
    }
    out.push_str(&format!("     * @returns {{{}}}\n", ret_type));
    out.push_str("     */\n");
}

fn build_sig_params(func: &ResolvedFunction, typescript_mode: bool) -> String {
    if func.params.is_empty() {
        return String::new();
    }
    let params: Vec<String> = func
        .params
        .iter()
        .map(|p: &ResolvedParam| {
            if typescript_mode {
                let ty_name: String = ts_type_name(&p.ty);
                format!("{}: {}", p.name, ty_name)
            } else {
                p.name.clone()
            }
        })
        .collect();
    params.join(", ")
}

fn ts_type_name(ty: &ResolvedTypeRef) -> String {
    match ty {
        ResolvedTypeRef::Primitive(p) => ts_primitive_type(p).to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => "StringView".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => "Buffer".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Ptr) => "bigint".to_owned(),
        ResolvedTypeRef::AbiType(AbiBuiltin::Void) => "void".to_owned(),
        ResolvedTypeRef::UserDefined(name) => name.clone(),
    }
}

fn ts_primitive_type(ty: &PrimitiveType) -> &'static str {
    match ty {
        PrimitiveType::U8 => "number",
        PrimitiveType::U16 => "number",
        PrimitiveType::U32 => "number",
        PrimitiveType::U64 => "bigint",
        PrimitiveType::I8 => "number",
        PrimitiveType::I16 => "number",
        PrimitiveType::I32 => "number",
        PrimitiveType::I64 => "bigint",
        PrimitiveType::F32 => "number",
        PrimitiveType::F64 => "number",
        PrimitiveType::Bool => "boolean",
    }
}

fn ts_return_type(returns: &Option<ResolvedTypeRef>) -> String {
    match returns {
        Some(ty) => {
            if is_void_type(ty) {
                "void".to_owned()
            } else {
                ts_type_name(ty)
            }
        }
        None => "void".to_owned(),
    }
}

fn is_void_type(ty: &ResolvedTypeRef) -> bool {
    matches!(ty, ResolvedTypeRef::AbiType(AbiBuiltin::Void))
}

fn contract_name_to_struct(name: &str) -> String {
    let converted: String = name
        .split('.')
        .map(|p: &str| {
            let mut chars: core::str::Chars<'_> = p.chars();
            match chars.next() {
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join("");
    format!("{converted}Contract")
}

fn contract_name_to_guest_trait(name: &str) -> String {
    let base: String = name
        .split('.')
        .map(|p: &str| {
            let mut chars: core::str::Chars<'_> = p.chars();
            match chars.next() {
                Some(c) => c.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join("");
    format!("{base}Plugin")
}

fn collect_type_imports(ir: &ValidatedIr) -> BTreeSet<String> {
    let mut imports: BTreeSet<String> = BTreeSet::new();
    for ty in &ir.types {
        imports.insert(ty.name.clone());
        for field in &ty.fields {
            collect_type_ref(&mut imports, &field.ty);
        }
    }
    for contract in &ir.contracts {
        for func in &contract.functions {
            for param in &func.params {
                collect_type_ref(&mut imports, &param.ty);
            }
            if let Some(ret_ty) = &func.returns {
                collect_type_ref(&mut imports, ret_ty);
            }
        }
    }
    imports
}

fn collect_type_ref(imports: &mut BTreeSet<String>, ty: &ResolvedTypeRef) {
    match ty {
        ResolvedTypeRef::UserDefined(name) => {
            imports.insert(name.clone());
        }
        ResolvedTypeRef::AbiType(AbiBuiltin::StringView) => {
            imports.insert("StringView".to_owned());
        }
        ResolvedTypeRef::AbiType(AbiBuiltin::Buffer) => {
            imports.insert("Buffer".to_owned());
        }
        _ => {}
    }
}

fn collect_js_exports(
    ir: &ValidatedIr,
    uses_string_view: bool,
    uses_buffer: bool,
) -> BTreeSet<String> {
    let mut exports: BTreeSet<String> = BTreeSet::new();
    for ty in &ir.types {
        exports.insert(ty.name.clone());
    }
    if uses_string_view {
        exports.insert("StringView".to_owned());
    }
    if uses_buffer {
        exports.insert("Buffer".to_owned());
    }
    exports
}

fn uses_builtin(ir: &ValidatedIr, builtin: AbiBuiltin) -> bool {
    for ty in &ir.types {
        for field in &ty.fields {
            if matches!(&field.ty, ResolvedTypeRef::AbiType(b) if b == &builtin) {
                return true;
            }
        }
    }
    for contract in &ir.contracts {
        for func in &contract.functions {
            for param in &func.params {
                if matches!(&param.ty, ResolvedTypeRef::AbiType(b) if b == &builtin) {
                    return true;
                }
            }
            if let Some(ret_ty) = &func.returns
                && matches!(ret_ty, ResolvedTypeRef::AbiType(b) if b == &builtin)
            {
                return true;
            }
        }
    }
    false
}
