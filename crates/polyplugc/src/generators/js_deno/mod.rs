//! js_deno generator — produces V8/deno_core-compatible TypeScript guest code.
//!
//! THIS FILE IS PART OF polyplugc.
//! Generates code using BigInt for all u64/pointer values (V8 has native BigInt).

use std::path::PathBuf;

use crate::error::CodegenError;
use crate::generators::CodeGenerator;
use crate::generators::GeneratedFile;
use crate::generators::GeneratedFiles;
use crate::ir::AbiBuiltin;
use crate::ir::PrimitiveType;
use crate::ir::ResolvedBundle;
use crate::ir::ResolvedContract;
use crate::ir::ResolvedDependency;
use crate::ir::ResolvedField;
use crate::ir::ResolvedFunction;
use crate::ir::ResolvedParam;
use crate::ir::ResolvedPlugin;
