//! polyplug guest library — Rust bindings for guest-side (plugin developer) use.
//!
//! This crate provides the ABI types, allocator hookup, and registration
//! helpers that plugin authors need to implement a polyplug contract.
//!
//! # Quick Start
//!
//! A minimal Rust plugin implementing a contract looks like this:
//!
//! ```rust,ignore
//! // In Cargo.toml: crate-type = ["cdylib"]
//! use polyplug_abi::*;
//!
//! // 1. Compute the contract ID at compile time (FNV-1a of "my.contract@1")
//! const MY_CONTRACT_ID: u64 = /* polyplugc generates this */;
//!
//! // 2. Implement your function with the generic dispatch signature
//! extern "C" fn my_fn(args: *const (), out: *mut ()) -> AbiError {
//!     // ... cast args/out, compute, write result
//!     AbiError::ok()
//! }
//!
//! // 3. Declare static interface
//! static MY_FNS: [FnPtr; 1] = [FnPtr(my_fn as *const ())];
//! static MY_VTABLE: GuestContractInterface = GuestContractInterface {
//!     contract_id: MY_CONTRACT_ID,
//!     contract_version: Version { major: 1, minor: 0, patch: 0 },
//!     dispatch_type: DispatchType::Native,
//!     create_instance: create_instance_stub,
//!     destroy_instance: destroy_instance_stub,
//!     dispatch: DispatchMechanisms {
//!         native: NativeDispatch {
//!             function_count: 1,
//!             functions: MY_FNS.as_ptr() as *const *const (),
//!         },
//!     },
//! };
//! static MY_DESCRIPTOR: PluginDescriptor = PluginDescriptor {
//!     name: StringView { ptr: b"my_plugin".as_ptr(), len: 9 },
//!     contract_name: StringView { ptr: b"my.contract".as_ptr(), len: 11 },
//!     version: Version { major: 1, minor: 0, patch: 0 },
//! };
//!
//! // 4. Export ABI version sentinel
//! #[unsafe(no_mangle)]
//! pub extern "C" fn polyplug_abi_version() -> u32 { POLYPLUG_ABI_VERSION }
//!
//! // 5. Export init function — registers vtables with the host
//! #[unsafe(no_mangle)]
//! pub unsafe extern "C" fn polyplug_init(
//!     host_abi: *const HostApi,
//!     _ctx: *const BundleInitContext,
//! ) -> AbiError {
//!     if host_abi.is_null() {
//!         return AbiError { code: AbiErrorCode::Generic, message: StringView::null() };
//!     }
//!     let host: &HostApi = unsafe { &*host_abi };
//!     unsafe {
//!         (host.register_guest_contract)(host_abi, &MY_DESCRIPTOR, &MY_VTABLE)
//!     }
//! }
//! ```
//!
//! # Status
//! Scaffold only. Full implementation is code-generated by `polyplugc`.
//!
//! # Known Limitation — single host vtable per process
//! The host [`HostApi`] pointer is stored in a process-wide [`OnceLock`]
//! ([`HOST_VTABLE`]): the FIRST runtime to initialize a plugin built against this
//! crate wins, and the slot is never overwritten. If one plugin dylib is loaded
//! by two `Runtime` instances in the same process, every host call the plugin
//! makes (cross-contract dispatch, alloc/free, error reporting) is routed to the
//! FIRST runtime's `HostApi`, not the one that owns the in-flight call. This
//! mirrors the once-per-process constraints of the CPython and CLR loaders: for
//! full isolation with a shared Rust guest dylib, use separate processes.

use std::sync::OnceLock;

use polyplug_abi::{AbiErrorCode, HostApi, StringView};

/// Wrapper for host interface pointer that implements Send + Sync.
/// The host interface is 'static and immutable, safe to share across threads.
#[repr(transparent)]
pub struct HostVtablePtr(pub *const polyplug_abi::HostApi);

// SAFETY: HostVtablePtr wraps a 'static host interface pointer provided by the host runtime.
// The interface is immutable and valid for the plugin's lifetime. Multiple threads may read
// from the same interface concurrently — the host ensures thread-safe access to interface data.
unsafe impl Send for HostVtablePtr {}

// SAFETY: The host interface is read-only 'static memory. Multiple threads may access the
// same interface concurrently without synchronization. The host runtime guarantees the interface
// remains valid and unchanged for the plugin's lifetime.
unsafe impl Sync for HostVtablePtr {}

/// Static storage for the host interface passed during polyplug_init.
/// Set once during initialization, then read-only for guest access.
///
/// # Known Limitation — first runtime wins
/// This is a process-wide `OnceLock`: the first `Runtime` to initialize a plugin
/// built against this crate populates it, and later `set` calls are ignored. A
/// plugin dylib shared by two `Runtime` instances in the same process therefore
/// sends ALL of its host calls to the first runtime's `HostApi`, regardless of
/// which runtime is driving the current call. For full isolation with a shared
/// Rust guest dylib, use separate processes (same constraint as the CPython and
/// CLR loaders).
static HOST_VTABLE: OnceLock<HostVtablePtr> = OnceLock::new();

