//! polyplug guest library — Rust bindings for guest-side (plugin developer) use.
//!
//! This crate provides the ABI types, allocator hookup, and registration
//! helpers that plugin authors need to implement a polyplug contract.
//!
//! # Quick Start
//!
//! With `polyplugc`-generated glue, a plugin author writes a trait impl plus
//! one exported factory per plugin. The generated `create_instance` calls the
//! factory for every instance the host creates and carries the returned
//! implementation (plus the [`HostContext`]) in `GuestContractInstance.data`:
//!
//! ```rust,ignore
//! // In Cargo.toml: crate-type = ["cdylib"]
//! use polyplug_guest::HostContext;
//!
//! #[path = "../generated/guest/mod.rs"]
//! mod generated;
//! use generated::contracts::MyContractGuestContract;
//!
//! struct Plugin {
//!     /// Host handle for this runtime — use it for alloc_string / log / peers.
//!     host: HostContext,
//! }
//!
//! impl MyContractGuestContract for Plugin {
//!     fn my_fn(&self, input: u32) -> Result<u32, polyplug_guest::GuestError> {
//!         self.host.log(polyplug_abi::types::LogLevel::Info, "guest.my_plugin", "called");
//!         Ok(input + 1)
//!     }
//! }
//!
//! /// Factory the generated `create_instance` glue calls for every instance.
//! /// The symbol name is fixed: `polyplug_create_<plugin_name>`.
//! #[unsafe(no_mangle)]
//! pub fn polyplug_create_my_plugin(host: HostContext) -> Box<dyn MyContractGuestContract> {
//!     Box::new(Plugin { host })
//! }
//!
//! /// ABI version sentinel — exported by the plugin crate itself.
//! #[unsafe(no_mangle)]
//! pub extern "C" fn polyplug_abi_version() -> u32 { polyplug_abi::POLYPLUG_ABI_VERSION }
//! ```
//!
//! `polyplug_init` itself is generated (`generated/guest/init.rs`): it only
//! registers the static interface tables. No implementation or host pointer is
//! ever stored in process-wide state.
//!
//! # Status
//! Scaffold only. Full implementation is code-generated by `polyplugc`.
//!
//! # Host access — instance flow, no statics
//! This crate holds NO process-wide state. The host [`HostApi`] pointer flows
//! from `create_instance` (where the host passes it) into a [`HostContext`]
//! that the generated glue hands to the author factory and stores in the
//! per-instance payload carried by `GuestContractInstance.data`. Every host
//! call (allocation, logging, peer dispatch) is therefore routed to the exact
//! `Runtime` that owns the in-flight call — multiple runtimes sharing one
//! plugin dylib in the same process stay fully isolated.

use core::error::Error;
use core::fmt;
use core::{mem, ptr, slice, str};

use polyplug_abi::types::LogLevel;
use polyplug_abi::{AbiError, AbiErrorCode, Buffer, CallArena, HostApi, StringView};

/// Per-instance handle to the host runtime that created a plugin instance.
///
/// Captured by the generated `create_instance` glue from the `HostApi`
/// pointer the host passes in, handed to the author factory
/// (`polyplug_create_<plugin>`), and stored in the instance payload. All
/// guest→host operations (allocation, logging, peer-caller resolution) go
/// through a `HostContext` — there is no process-wide host storage.
#[derive(Clone, Copy)]
pub struct HostContext {
    /// The host's function table for the owning runtime.
    host: *const HostApi,
}

// SAFETY: HostContext wraps a host interface pointer provided by the host runtime.
// The interface is immutable and valid for the plugin's lifetime. Multiple threads may read
// from the same interface concurrently — the host ensures thread-safe access to interface data.
unsafe impl Send for HostContext {}

// SAFETY: The host interface is read-only memory owned by the runtime. Multiple threads may
// access the same interface concurrently without synchronization. The host runtime guarantees
// the interface remains valid and unchanged for the plugin's lifetime.
unsafe impl Sync for HostContext {}

impl HostContext {
    /// Wrap a raw `HostApi` pointer received from the host.
    ///
    /// # Safety
    /// `host` must be a valid `HostApi` pointer provided by the host runtime
    /// (e.g. the first argument of `create_instance` or `polyplug_init`) and
    /// must remain valid for as long as this context is used.
    pub unsafe fn new(host: *const HostApi) -> Self {
        Self { host }
    }

    /// The raw `HostApi` pointer, for generated glue and ABI-level calls.
    pub fn as_ptr(self) -> *const HostApi {
        self.host
    }

    /// Returns `true` when this context carries no host pointer.
    pub fn is_null(self) -> bool {
        self.host.is_null()
    }

    /// Allocate a `StringView` from a `&str` using this runtime's host allocator.
    ///
    /// Allocates through `HostApi.alloc` (align 1), so the bytes are owned by
    /// the host and never link a separate allocator copy into the plugin dylib.
    /// The receiver (host) is responsible for freeing the memory via
    /// `host.free(host, ptr, len, 1)`.
    ///
    /// # Errors
    /// Returns `Err(GuestError)` if this context is null or allocation fails.
    pub fn alloc_string(self, s: &str) -> Result<StringView, GuestError> {
        if self.host.is_null() {
            return Err(GuestError {
                code: AbiErrorCode::Generic,
                message: "host interface unavailable".to_string(),
            });
        }
        let bytes: &[u8] = s.as_bytes();
        // SAFETY: self.host is non-null (checked above) and valid per the
        // HostContext::new contract. `alloc` is a valid function pointer set by the host.
        let ptr: *mut u8 = unsafe { ((*self.host).alloc)(self.host, bytes.len(), 1) };
        if ptr.is_null() {
            return Err(GuestError {
                code: AbiErrorCode::Generic,
                message: "allocation failed".to_string(),
            });
        }
        // SAFETY: ptr is non-null (checked above) and was allocated by host.alloc
        // with size bytes.len() and align 1. The source bytes.as_ptr() is valid for
        // bytes.len() bytes. The destination is valid for bytes.len() bytes.
        unsafe { ptr::copy_nonoverlapping(bytes.as_ptr(), ptr, bytes.len()) };
        Ok(StringView {
            ptr,
            len: bytes.len(),
        })
    }

    /// Allocate a host-owned ABI buffer containing `bytes`.
    ///
    /// Generated internal-profile adapters use this for owned `Vec<u8>` returns;
    /// ownership transfers to the receiving host through the returned [`Buffer`].
    pub fn alloc_buffer(self, bytes: &[u8]) -> Result<Buffer, GuestError> {
        if self.host.is_null() {
            return Err(GuestError {
                code: AbiErrorCode::Generic,
                message: "host interface unavailable".to_owned(),
            });
        }
        if bytes.is_empty() {
            return Ok(Buffer {
                ptr: ptr::null_mut(),
                len: 0,
                cap: 0,
            });
        }
        // SAFETY: self.host was checked non-null above and points at a valid host ABI table.
        let ptr: *mut u8 = unsafe { ((*self.host).alloc)(self.host, bytes.len(), 1) };
        if ptr.is_null() {
            return Err(GuestError {
                code: AbiErrorCode::Generic,
                message: "allocation failed".to_owned(),
            });
        }
        // SAFETY: ptr is a non-null allocation for bytes.len() bytes; source and destination do not overlap.
        unsafe { ptr::copy_nonoverlapping(bytes.as_ptr(), ptr, bytes.len()) };
        Ok(Buffer {
            ptr,
            len: bytes.len(),
            cap: bytes.len(),
        })
    }

    /// Log a diagnostic into this runtime's logging funnel (`HostApi.log`).
    ///
    /// Routes to the same sink as the host's `RuntimeConfig::log` callback (or
    /// its stderr default). `scope` should be a short stable tag, e.g.
    /// `"guest.<plugin-name>"`. No-op when this context is null.
    pub fn log(self, level: LogLevel, scope: &str, message: &str) {
        if self.host.is_null() {
            return;
        }
        let scope_view = StringView {
            ptr: scope.as_ptr(),
            len: scope.len(),
        };
        let message_view = StringView {
            ptr: message.as_ptr(),
            len: message.len(),
        };
        // SAFETY: self.host is non-null (checked above) and valid per the
        // HostContext::new contract; `log` is always provided by the runtime. Both
        // views borrow live UTF-8 Rust string data that outlives the synchronous
        // call, matching the field's documented ownership contract.
        unsafe { ((*self.host).log)(self.host, level as u32, scope_view, message_view) }
    }
}

// ─── Return buffer for variable-size native returns ─────────────────────────────

/// A per-instance return-value buffer for a native guest's variable-size returns.
///
/// A native guest that returns a `StringView`, `Buffer`, or an `Array<T>` wrapper
/// must hand back memory that stays valid until the host copies it out. Unlike
/// [`HostContext::alloc_string`] — which allocates through the host allocator and
/// relies on the host to free each value — `ReturnArena` owns one reusable buffer
/// that it rewinds on every call. This is the borrowed-return model: zero
/// per-call host allocation, zero host free, and every view it hands out is valid
/// only until the next [`reset`](Self::reset).
///
/// Hold one on the plugin impl (behind a `RefCell` or `&mut self`), call
/// [`reset`](Self::reset) at the start of each method that returns variable-size
/// data, then use [`alloc_str`](Self::alloc_str) / [`alloc_array`](Self::alloc_array)
/// to build the return value. Returns larger than the primary buffer spill into
/// host-allocated overflow blocks that `reset` reclaims, so the capacity is a
/// tuning hint, not a hard cap.
pub struct ReturnArena {
    /// Backing storage for the primary bump region. Boxed so its heap address is
    /// stable across moves of `ReturnArena` — `arena` caches raw pointers into it.
    _buf: Box<[u8]>,
    /// Bump allocator over `_buf`, with the host for overflow reclamation.
    arena: CallArena,
}

// SAFETY: `ReturnArena` solely owns its `_buf` and the `CallArena` pointers refer
// only into that owned buffer (plus a host pointer used solely for overflow
// alloc/free). No pointer aliases memory owned elsewhere, so moving the whole
// arena to another thread is sound. It is deliberately NOT `Sync`: concurrent
// shared access would race the bump cursor — wrap it in a `Mutex`/`RefCell` (a
// `Mutex<ReturnArena>` is `Sync`) to satisfy a `Send + Sync` guest trait bound.
unsafe impl Send for ReturnArena {}

impl ReturnArena {
    /// Create a return buffer with a `capacity`-byte primary region, using `host`
    /// only to allocate/free overflow blocks for returns that exceed it.
    pub fn new(host: HostContext, capacity: usize) -> ReturnArena {
        let mut buf: Box<[u8]> = vec![0_u8; capacity].into_boxed_slice();
        // `CallArena` stores raw pointers into `buf`. A `Box<[u8]>`'s heap data
        // keeps its address when the owning `ReturnArena` is moved (only the box
        // pointer moves), so the cached pointers stay valid for the arena's life.
        let arena: CallArena = CallArena::new(&mut buf, host.as_ptr());
        ReturnArena { _buf: buf, arena }
    }

    /// Rewind the buffer, invalidating every view returned since the last reset
    /// and reclaiming any overflow blocks. Call at the start of each method that
    /// returns variable-size data.
    pub fn reset(&mut self) {
        self.arena.reset();
    }

    /// Copy `s` into the buffer and return a `StringView` borrowing it, valid
    /// until the next [`reset`](Self::reset). An empty string returns an empty
    /// view without allocating.
    pub fn alloc_str(&mut self, s: &str) -> StringView {
        let bytes: &[u8] = s.as_bytes();
        if bytes.is_empty() {
            return StringView {
                ptr: ptr::null(),
                len: 0,
            };
        }
        let dst: *mut u8 = self.arena.alloc(bytes.len(), 1);
        if dst.is_null() {
            return StringView {
                ptr: ptr::null(),
                len: 0,
            };
        }
        // SAFETY: `dst` is non-null (checked), came from the arena sized for
        // `bytes.len()` bytes at align 1; the source is valid for that many bytes
        // and the regions do not overlap (fresh arena allocation).
        unsafe { ptr::copy_nonoverlapping(bytes.as_ptr(), dst, bytes.len()) };
        StringView {
            ptr: dst as *const u8,
            len: bytes.len(),
        }
    }

    /// Copy `xs` into the buffer as a contiguous array and return
    /// `(items, len)` for an `ArrayOf_T { items, len }` wrapper — `items` is the
    /// element pointer as a `u64`, `len` the element count. Valid until the next
    /// [`reset`](Self::reset). An empty slice returns `(0, 0)`.
    ///
    /// Any `StringView` (or nested array) embedded in an element must already
    /// point at buffer memory from a prior `alloc_str`/`alloc_array` on the same
    /// `ReturnArena`, so the whole return graph shares one lifetime.
    pub fn alloc_array<T: Copy>(&mut self, xs: &[T]) -> (u64, u64) {
        if xs.is_empty() {
            return (0, 0);
        }
        let size: usize = mem::size_of_val(xs);
        let align: usize = mem::align_of::<T>();
        let dst: *mut u8 = self.arena.alloc(size, align);
        if dst.is_null() {
            return (0, 0);
        }
        // SAFETY: `dst` is non-null (checked), came from the arena sized for
        // `size` bytes at `align_of::<T>()`, so it is aligned for `T` and holds
        // `xs.len()` elements. `T: Copy`, so the bytewise copy is a valid clone,
        // and source/destination do not overlap (fresh arena allocation).
        unsafe { ptr::copy_nonoverlapping(xs.as_ptr(), dst as *mut T, xs.len()) };
        (dst as u64, xs.len() as u64)
    }

    /// Copy ABI values into the arena without invoking their destructors.
    ///
    /// # Safety
    /// `T` must be an ABI plain-data type with no destructor; generated bindings
    /// satisfy this because the copied descriptors transfer ownership to the host.
    pub unsafe fn alloc_abi_array<T>(&mut self, xs: &[T]) -> (u64, u64) {
        if xs.is_empty() {
            return (0, 0);
        }
        let size: usize = mem::size_of_val(xs);
        let align: usize = mem::align_of::<T>();
        let dst: *mut u8 = self.arena.alloc(size, align);
        if dst.is_null() {
            return (0, 0);
        }
        // SAFETY: dst is a non-null arena allocation for xs.len() T values; source and destination do not overlap.
        unsafe { ptr::copy_nonoverlapping(xs.as_ptr(), dst as *mut T, xs.len()) };
        (dst as u64, xs.len() as u64)
    }
}

